#!/usr/bin/env python3
"""Generate kernel/src/gpu/stolen_ids.rs: the PCI device ids Linux's x86
early quirk (arch/x86/kernel/early-quirks.c, intel_early_ids) handles with
gen11_early_ops, expanded by the preprocessor from include/drm/intel/pciids.h.

    python3 tools/gen_intel_stolen_ids.py
"""
import os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = os.path.expanduser("~/.cache/nopeekos/i915-work/linux-6.18.55")
OUT = os.path.join(ROOT, "kernel/src/gpu/stolen_ids.rs")
QUIRK = os.path.expanduser("~/.cache/nopeekos/linux-src/linux-6.18.55/arch/x86/kernel/early-quirks.c")

src = open(QUIRK).read()
families = re.findall(r"INTEL_(\w+)_IDS\(INTEL_VGA_DEVICE, &gen11_early_ops\)", src)
if not families:
    sys.exit("no gen11_early_ops families in early-quirks.c")
c = '#include <drm/intel/pciids.h>\n#define ID(d, ...) NPKID d\n'
c += "".join(f"INTEL_{f}_IDS(ID)\n" for f in families)
pre = subprocess.run(["gcc", "-E", "-P", f"-I{L}/include", "-x", "c", "-"],
                     input=c, capture_output=True, text=True, check=True).stdout
ids = sorted({int(x, 16) for x in re.findall(r"NPKID (0x[0-9A-Fa-f]+)", pre)})
lines = ["// Generated by tools/gen_intel_stolen_ids.py from Linux 6.18.55; do not edit.",
         f"// intel_early_ids with gen11_early_ops: {', '.join(families)}.", "",
         f"pub const GEN11_STOLEN_IDS: [u16; {len(ids)}] = ["]
for i in range(0, len(ids), 8):
    lines.append("    " + ", ".join(f"{x:#06x}" for x in ids[i:i + 8]) + ",")
lines.append("];")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(ids)} ids from {len(families)} families")
