#!/usr/bin/env python3
"""Generate kernel/src/cpu_vulns_table.rs from Linux's tables.

Reads cpu_vuln_whitelist and cpu_vuln_blacklist from
arch/x86/kernel/cpu/common.c, amd_tsa_microcode from amd.c and the model
numbers from include/asm/intel-family.h, and writes them as Rust arrays in
the same order (the first matching row wins, as in x86_match_cpu).

Usage: tools/gen_cpu_vulns.py <linux-src-dir>
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]) / "arch/x86"
common = (src / "kernel/cpu/common.c").read_text()
amd = (src / "kernel/cpu/amd.c").read_text()
family = (src / "include/asm/intel-family.h").read_text()

ifm = {m.group(1): (int(m.group(2), 0), int(m.group(3), 0))
       for m in re.finditer(r"#define\s+(INTEL_\w+)\s+IFM\((\d+),\s*(0x[0-9A-Fa-f]+|\d+)\)", family)}


def block(text, name):
    start = text.index(name)
    return text[start:text.index("};", start)]


def flags(expr):
    return " | ".join(f"{f.strip()}" for f in expr.split("|"))


out = ["// Generated by tools/gen_cpu_vulns.py from Linux "
       f"{Path(sys.argv[1]).name}; do not edit.",
       "",
       "use super::{Row, Vendor::*, *};",
       "",
       "/// `cpu_vuln_whitelist` (common.c), Intel and AMD rows.",
       "pub const WHITELIST: &[Row] = &["]
for line in block(common, "cpu_vuln_whitelist[]").splitlines():
    line = line.strip()
    m = re.match(r"VULNWL_INTEL\((\w+),\s*(.+)\),", line)
    if m:
        fam, model = ifm[m.group(1)]
        out.append(f"    Row {{ vendor: Intel, family: Some({fam:#x}), model: Some({model:#x}), max_step: 0xF, bits: {flags(m.group(2))} }}, // {m.group(1)}")
        continue
    m = re.match(r"VULNWL_AMD\((\w+),\s*(.+)\),", line)
    if m:
        fam = "None" if m.group(1) == "X86_FAMILY_ANY" else f"Some({int(m.group(1), 0):#x})"
        out.append(f"    Row {{ vendor: Amd, family: {fam}, model: None, max_step: 0xF, bits: {flags(m.group(2))} }},")
        continue
    m = re.match(r"VULNWL\((INTEL|AMD),\s*(\w+),\s*X86_MODEL_ANY,\s*(.+)\),", line)
    if m:
        vendor = "Intel" if m.group(1) == "INTEL" else "Amd"
        out.append(f"    Row {{ vendor: {vendor}, family: Some({int(m.group(2), 0):#x}), model: None, max_step: 0xF, bits: {flags(m.group(3))} }},")
out.append("];")
out.append("")
out.append("/// `cpu_vuln_blacklist` (common.c), Intel and AMD rows.")
out.append("pub const BLACKLIST: &[Row] = &[")
for line in block(common, "cpu_vuln_blacklist[]").splitlines():
    line = line.strip()
    m = re.match(r"VULNBL_INTEL_STEPS\((\w+),\s*(\w+),\s*(.+)\),", line)
    if m:
        fam, model = ifm[m.group(1)]
        step = 0xF if m.group(2) == "X86_STEP_MAX" else int(m.group(2), 0)
        out.append(f"    Row {{ vendor: Intel, family: Some({fam:#x}), model: Some({model:#x}), max_step: {step:#x}, bits: {flags(m.group(3))} }}, // {m.group(1)}")
        continue
    m = re.match(r"VULNBL_AMD\((\w+),\s*(.+)\),", line)
    if m:
        out.append(f"    Row {{ vendor: Amd, family: Some({int(m.group(1), 0):#x}), model: None, max_step: 0xF, bits: {flags(m.group(2))} }},")
out.append("];")
out.append("")
out.append("/// `amd_tsa_microcode` (amd.c): (family, model, stepping, minimum revision).")
out.append("pub const AMD_TSA_MICROCODE: &[(u32, u32, u32, u32)] = &[")
for m in re.finditer(r"ZEN_MODEL_STEP_UCODE\((\w+),\s*(\w+),\s*(\w+),\s*(\w+)\)", block(amd, "amd_tsa_microcode[]")):
    out.append(f"    ({int(m.group(1), 0):#x}, {int(m.group(2), 0):#x}, {int(m.group(3), 0):#x}, {int(m.group(4), 0):#010x}),")
out.append("];")

Path(__file__).resolve().parent.parent.joinpath("kernel/src/cpu_vulns_table.rs").write_text("\n".join(out) + "\n")
print(f"{sum(1 for l in out if 'Row {' in l)} rows")
