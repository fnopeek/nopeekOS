#!/usr/bin/env python3
"""Generate kernel/src/drivers/amd_vi_regs.rs from tools/amd_vi_regs.list:
the AMD-Vi constants of Linux 6.18.55 drivers/iommu/amd, each computed by
GCC with the flags of the kernel build, the way
tools/wasm/gpu_amd_renoir/gen_regs.py computes amdgpu's (its machinery is
reused here).

    python3 tools/amd-vi-regs.py            # rewrite the file
    python3 tools/amd-vi-regs.py --check    # fail if it is not what it writes
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools/wasm/gpu_amd_renoir"))
check = "--check" in sys.argv
sys.argv = [sys.argv[0]]
import gen_regs as g  # noqa: E402

LIST = os.path.join(ROOT, "tools/amd_vi_regs.list")
OUT = os.path.join(ROOT, "kernel/src/drivers/amd_vi_regs.rs")
IOMMU = os.path.join(g.L, "drivers/iommu/amd")


def main():
    groups, cur = [], ["", []]
    for raw in open(LIST):
        line = raw.strip()
        if not line or (line.startswith("#") and not line.startswith("# ")):
            continue
        if line.startswith("# "):
            if cur[1]:
                groups.append(cur)
            cur = [line[2:], []]
            continue
        m = re.match(r"^(\w+)(?:\s*=\s*(.+?))?\s*@\s*(\S+)$", line)
        if not m:
            sys.exit(f"amd_vi_regs.list: cannot read: {line}")
        cur[1].append((m.group(1), m.group(2) or m.group(1), m.group(3)))
    groups.append(cur)
    # The first block of comment lines is the list's own header.
    groups = [gr for gr in groups if gr[1]]
    by_file = {}
    for _, items in groups:
        for name, expr, f in items:
            by_file.setdefault(f, {})[name] = expr
    vals = {}
    for f, exprs in by_file.items():
        rel = os.path.relpath(os.path.join(IOMMU, f), g.DRV)
        vals.update(g.values(exprs, f'#include "{rel}"\n'))
    out = ["// Generated by tools/amd-vi-regs.py from Linux 6.18.55 drivers/iommu/amd; do not edit.", ""]
    for title, items in groups:
        out.append(f"// {title}")
        for name, expr, f in items:
            src = g.where(name, [os.path.join(IOMMU, f)]) if expr == name else f"The value of `{expr}` in {f}"
            if src and src.startswith(".."):
                src = os.path.relpath(os.path.join(g.AMD, src), g.L)
            v = vals[name]
            out.append(f"/// {src or f}")
            out.append(f"pub const {name}: {g.rust_type(v)} = {v:#x};")
        out.append("")
    text = "\n".join(out)
    if check:
        if open(OUT).read() != text:
            sys.exit(f"{OUT} is not what amd-vi-regs.py writes")
    else:
        open(OUT, "w").write(text)
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
