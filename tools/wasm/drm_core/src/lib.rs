//! drm_core: the parts of Linux's DRM core (`drivers/gpu/drm`, rpi-6.18)
//! that more than one display module needs, ported once.
//!
//! no_std + alloc; the same library builds for the std test harness and
//! for each module's wasm32 build. Every part follows its Linux file; the
//! hardware it reaches is the caller's (an I2C transfer is a closure).
//!
//! - [`drm_edid`]: reading an EDID over DDC and what a connector takes
//!   from it.
//! - [`drm_connector`]: the connector and display info EDID fills.
//! - [`i2c`]: an I2C message, as DDC transfers carry it.
//! - [`linux`]: printk and errno.
//! - [`regs`]: DRM's constants and tables, generated by `gen_regs.py`.

#![cfg_attr(not(test), no_std)]
#![allow(non_camel_case_types, non_snake_case)]

extern crate alloc;

pub mod drm_connector;
pub mod drm_edid;
pub mod i2c;
pub mod linux;
pub mod regs;
