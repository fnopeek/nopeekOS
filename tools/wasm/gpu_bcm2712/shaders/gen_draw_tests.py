#!/usr/bin/env python3
"""Generate core/testdata/draw/*.txt: what v3dv records for render passes
of the module's drawing model, for core/src/tests_draw.rs, which records
the same passes with core/src/v3d_draw.rs and compares every byte.

Each scenario runs v3dg (v3dg.c, built against v3dv) behind Mesa's v3d
drm-shim with draw/rect.vert and draw/draw.frag. A file holds the scenario
(image size, render area, revision, draws), v3dg's meta lines (programs,
prog_data, uniform lists, submit parameters) and every buffer of the job's
binning list, render list and indirect state as hex, trailing zero bytes
dropped.

    python3 gen_draw_tests.py            # rewrite the files
    python3 gen_draw_tests.py --check    # fail if they are not what it would write
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_shaders  # noqa: E402

OUT = os.path.join(HERE, "..", "core", "testdata", "draw")
SHIM = os.path.join(gen_shaders.BUILD, "src", "broadcom", "drm-shim", "libv3d_noop_drm_shim.so")


def alternating(n):
    """`n` draws alternating two pipelines, each with its own rectangle."""
    out = []
    for i in range(n):
        x, y = (i * 7) % 200, (i * 5) % 100
        out.append("%d:%d,%d,%d,%d" % (1 + i % 2, x, y, x + 20 + i % 9, y + 10 + i % 5))
    return out


# name, width, height, extra v3dg options, draws
SCENARIOS = [
    ("one_64x64", 64, 64, [], ["1:0,0,64,64"]),
    ("nine_kinds_256x128", 256, 128, [],
     ["%d:%d,%d,%d,%d" % (k, 4 * k, 3 * k, 4 * k + 100, 3 * k + 60) for k in range(1, 10)]),
    # The glass kinds read flat varyings from rect.vert.
    ("glass_kinds_256x128", 256, 128, [], ["1:0,0,256,128", "10:10,10,120,100", "11:130,10,250,100", "4:0,0,256,128"]),
    ("three_1920x1080", 1920, 1080, [], ["1:0,0,1920,1080", "7:100,200,900,700", "3:1500,40,1910,1070"]),
    ("three_3840x2160", 3840, 2160, [], ["1:0,0,3840,2160", "5:10,10,3000,2000", "9:2000,1000,3840,2160"]),
    ("sub_area_256x128", 256, 128, ["-a", "30,20,100,50"], ["1:30,20,130,70", "4:40,30,90,60"]),
    ("sub_area_aligned_512x256", 512, 256, ["-a", "64,64,128,128"], ["2:64,64,192,192", "6:70,80,150,170"]),
    ("sub_area_edge_300x200", 300, 200, ["-a", "64,128,236,72"], ["8:64,128,300,200"]),
    ("same_pipeline_256x128", 256, 128, [],
     ["2:0,0,10,10", "2:0,0,10,10", "2:5,5,20,20", "2:5,5,20,20", "5:1,1,9,9", "5:1,1,9,9", "2:5,5,20,20"]),
    ("rev10_256x128", 256, 128, ["-r", "10"], ["1:0,0,256,128", "7:40,40,120,70", "7:50,50,60,60"]),
    ("many_draws_640x480", 640, 480, [], alternating(90)),
    # The fourth draw's fragment stream would fit the first buffer without
    # the uniform prefetch slot v3dv_write_uniforms reserves.
    ("prefetch_slot_256x128", 256, 128, [],
     ["8:0,0,100,50", "4:10,10,90,60", "5:20,20,200,100", "3:30,30,60,60", "4:0,64,256,128"]),
]


def run(tool, tmp, name, w, h, opts, draws):
    out = os.path.join(tmp, name)
    os.makedirs(out)
    env = dict(os.environ, LD_PRELOAD=SHIM, MESA_SHADER_CACHE_DISABLE="1")
    env.pop("V3D_DEBUG", None)
    cmd = [tool] + opts + [os.path.join(tmp, "rect.vert.spv"), os.path.join(tmp, "draw.frag.spv"), str(w), str(h),
                           out] + draws
    r = subprocess.run(cmd, env=env, capture_output=True, text=True)
    if r.returncode:
        sys.exit("gen_draw_tests: v3dg %s failed:\n%s" % (name, r.stderr[-4000:]))
    lines = ["# Generated by shaders/gen_draw_tests.py from v3dg (v3dv %s); do not edit." % "26.2.4",
             "scenario %s" % name]
    for d in draws:
        k, rect = d.split(":")
        lines.append("draw %s %s" % (k, " ".join(rect.split(","))))
    for line in open(os.path.join(out, "meta")).read().splitlines():
        lines.append(line)
        parts = line.split()
        if parts[0] != "bo":
            continue
        data = open(os.path.join(out, "bo-%s.bin" % parts[2]), "rb").read()
        assert len(data) == int(parts[3])
        lines.append("bytes %s %s" % (parts[2], data.rstrip(b"\0").hex() or "-"))
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    with tempfile.TemporaryDirectory() as tmp:
        tool = gen_shaders.build_v3dc(tmp, "v3dg")
        for src, spv in (("rect.vert", "rect.vert.spv"), ("draw.frag", "draw.frag.spv")):
            subprocess.run(["glslangValidator", "-V", "--target-env", "vulkan1.3", "-o", os.path.join(tmp, spv),
                            os.path.join(HERE, "draw", src)], check=True, capture_output=True)
        texts = {name: run(tool, tmp, name, w, h, opts, draws) for name, w, h, opts, draws in SCENARIOS}
    if check:
        bad = [n for n, t in texts.items()
               if not os.path.exists(os.path.join(OUT, n + ".txt")) or open(os.path.join(OUT, n + ".txt")).read() != t]
        if bad:
            sys.exit("gen_draw_tests: out of date: " + ", ".join(bad))
        return
    os.makedirs(OUT, exist_ok=True)
    for n, t in texts.items():
        open(os.path.join(OUT, n + ".txt"), "w").write(t)
    print("gen_draw_tests: %d scenarios" % len(texts))


if __name__ == "__main__":
    main()
