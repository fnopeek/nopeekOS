#!/usr/bin/env python3
"""Generate core/src/regs.rs from the vc4 sources, with GCC doing the
arithmetic (the method of tools/pi5/gen_vc4_regs.py, whose compile helpers
it uses).

Every value is a C function returning a Linux expression, compiled with
the pi5 oracle's kernel compile line and read off the `movl $N, %eax` GCC
emits. vc4's register macros look at `hvs->vc4->gen` at run time, so each
function has a `struct vc4_hvs *hvs` and a `struct vc4_dev *vc4` of the
generation it is evaluated for: VC4_GEN_6_C (BCM2712 C1) and VC4_GEN_6_D
(D0).

regs.list, one item per line:

    # text              a comment line in the output
    @ file.c            later items are compiled with file.c included (its
                        static tables); `@` alone goes back to the headers
    NAME                NAME, the same on both generations
    NAME ~              NAME per generation: [C1, D0]
    NAME(x) [n]         NAME(0) .. NAME(n - 1)
    NAME(x) [n] ~       the same per generation: [[..; n]; 2]
    RUST = expr         a C expression, the same on both generations
    RUST[n] = expr      expr for i = 0 .. n - 1

    python3 gen_regs.py           # rewrite core/src/regs.rs
    python3 gen_regs.py --check   # fail if it is not what it would write
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "pi5"))
import gen_vc4_regs as g  # noqa: E402

LIST = os.path.join(HERE, "regs.list")
OUT = os.path.join(HERE, "core", "src", "regs.rs")
HEADERS = [f"{g.V}/{h}" for h in ["vc4_drv.h", "vc4_regs.h", "vc4_hdmi.h", "vc4_hdmi_regs.h"]]
GENS = ["VC4_GEN_6_C", "VC4_GEN_6_D"]


def parse():
    items = []
    src = None
    for raw in open(LIST):
        line = raw.rstrip("\n")
        if not line.strip():
            continue
        if line.startswith("#"):
            items.append(("comment", line[1:].strip()))
            continue
        if line.startswith("@"):
            src = line[1:].strip() or None
            continue
        per_gen = line.rstrip().endswith("~")
        line = line.rstrip().rstrip("~").rstrip()
        m = re.fullmatch(r"(\w+)\[(\d+)\]\s*=\s*(.+)", line)
        if m:
            items.append(("table", m.group(1), int(m.group(2)), m.group(3), per_gen, src))
            continue
        m = re.fullmatch(r"(\w+)\s*=\s*(.+)", line)
        if m:
            items.append(("expr", m.group(1), m.group(2), per_gen, src))
            continue
        m = re.fullmatch(r"(\w+)\(x\)\s*\[(\d+)\]", line)
        if m:
            items.append(("table", m.group(1), int(m.group(2)), f"{m.group(1)}(i)", per_gen, src))
            continue
        m = re.fullmatch(r"(\w+)", line)
        if m:
            items.append(("expr", m.group(1), m.group(1), per_gen, src))
            continue
        sys.exit(f"regs.list: cannot read {raw!r}")
    return items


def func(name, gen, expr):
    return (f"unsigned {name}(void) {{ struct vc4_dev v_ = {{ .gen = {gen} }}; "
            f"struct vc4_hvs h_ = {{ .vc4 = &v_ }}; struct vc4_hvs *hvs = &h_; struct vc4_dev *vc4 = &v_; "
            f"(void)hvs; (void)vc4; return (unsigned)({expr}); }}")


def evaluate(items):
    """{(gen index, key): value} for every value the items need."""
    by_src = {}
    for it in items:
        if it[0] == "comment":
            continue
        by_src.setdefault(it[-1], []).append(it)
    vals = {}
    for src, its in by_src.items():
        body = []
        for it in its:
            for gi, gen in enumerate(GENS):
                if it[0] == "expr":
                    body.append(func(f"v{gi}_{it[1]}", gen, it[2]))
                else:
                    for i in range(it[2]):
                        body.append(func(f"v{gi}_{it[1]}_{i}", gen, f"({{ unsigned i = {i}; (void)i; {it[3]}; }})"))
        headers = HEADERS + ([f"{g.V}/{src}"] if src else [])
        asm = g.compile_asm("\n".join(body) + "\n", headers)
        got = g.ints(asm)
        for k, v in got.items():
            vals[k] = v
    return vals


def main():
    check = "--check" in sys.argv[1:]
    items = parse()
    v = evaluate(items)
    o = [
        "//! vc4's registers, fields and tables for the BCM2712, generated by",
        "//! `gen_regs.py` from `regs.list` and Linux rpi-6.18 (`drivers/gpu/drm/vc4`).",
        "//! A value that differs between the generations is `[C1, D0]`. Do not edit.",
        "",
        "#![allow(dead_code)]",
        "",
    ]
    for it in items:
        if it[0] == "comment":
            o.append("")
            o.append(f"// {it[1]}")
            continue
        name = it[1]
        if it[0] == "expr":
            a, b = v[f"v0_{name}"], v[f"v1_{name}"]
            if it[3]:
                o.append(f"pub const {name}: [u32; 2] = [{a:#x}, {b:#x}];")
            else:
                if a != b:
                    sys.exit(f"{name} differs between the generations ({a:#x}, {b:#x}): mark it `~`")
                o.append(f"pub const {name}: u32 = {a:#x};")
        else:
            n = it[2]
            rows = [[v[f"v{gi}_{name}_{i}"] for i in range(n)] for gi in range(2)]
            fmt = lambda r: "[" + ", ".join(f"{x:#x}" for x in r) + "]"
            if it[4]:
                o.append(f"pub const {name}: [[u32; {n}]; 2] = [{fmt(rows[0])}, {fmt(rows[1])}];")
            else:
                if rows[0] != rows[1]:
                    sys.exit(f"{name} differs between the generations: mark it `~`")
                o.append(f"pub const {name}: [u32; {n}] = {fmt(rows[0])};")
    text = "\n".join(o).rstrip() + "\n"
    if check:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit(f"{OUT} is not what gen_regs.py writes")
        return
    open(OUT, "w").write(text)


if __name__ == "__main__":
    main()
