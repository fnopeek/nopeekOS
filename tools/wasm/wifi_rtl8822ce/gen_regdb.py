#!/usr/bin/env python3
"""Generate src/regdb.rs: the DFS region of every country in wireless-regdb
and the country list of rtw88's rtw_reg_map.

The DFS region decides the EDCCA mode (phy.c rtw_phy_adaptivity_set_mode);
cfg80211 takes it from the regulatory database for the country in force.
rtw_reg_map (regd.c) decides whether the efuse country code counts as
programmed.

    python3 gen_regdb.py /path/to/wireless-regdb/db.txt
"""
import os
import re
import sys

D = os.path.expanduser(
    "~/.cache/nopeekos/linux-src/linux-6.18.26/"
    "drivers/net/wireless/realtek/rtw88")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src",
                   "regdb.rs")

# include/uapi/linux/nl80211.h `enum nl80211_dfs_regions`.
DFS = {"": 0, "DFS-FCC": 1, "DFS-ETSI": 2, "DFS-JP": 3}


def regdb(path):
    out = []
    for line in open(path, errors="ignore"):
        m = re.match(r"country\s+([0-9A-Z]{2}):\s*(\S*)", line)
        if m:
            out.append((m.group(1), DFS[m.group(2)]))
    return sorted(out)


def reg_map():
    src = open(os.path.join(D, "regd.c"), errors="ignore").read()
    body = src[src.index("rtw_reg_map[] = {"):]
    body = body[:body.index("};")]
    return sorted(set(re.findall(r'COUNTRY_REGD_ENT\("([0-9A-Z]{2})"', body)))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    countries = regdb(sys.argv[1])
    rtw = reg_map()
    lines = [
        "//! Generated by gen_regdb.py from wireless-regdb db.txt and rtw88",
        "//! regd.c. Do not edit; run the generator.",
        "",
        "/// `enum nl80211_dfs_regions`.",
        "pub const NL80211_DFS_UNSET: u8 = 0;",
        "pub const NL80211_DFS_ETSI: u8 = 2;",
        "pub const NL80211_DFS_JP: u8 = 3;",
        "",
        "/// wireless-regdb: country and its DFS region, sorted by country.",
        "const DFS_REGION: [([u8; 2], u8); %d] = [" % len(countries),
    ]
    for c, d in countries:
        lines.append("    (*b\"%s\", %d)," % (c, d))
    lines += [
        "];",
        "",
        "/// regd.c `rtw_reg_map`: the countries rtw88 knows by name, sorted.",
        "const RTW_REG_MAP: [[u8; 2]; %d] = [" % len(rtw),
    ]
    for c in rtw:
        lines.append("    *b\"%s\"," % c)
    lines += [
        "];",
        "",
        "/// The DFS region cfg80211 sets for `alpha2`; unset for a country",
        "/// the database does not list.",
        "pub fn dfs_region(alpha2: [u8; 2]) -> u8 {",
        "    DFS_REGION.binary_search_by(|e| e.0.cmp(&alpha2))",
        "        .map_or(NL80211_DFS_UNSET, |i| DFS_REGION[i].1)",
        "}",
        "",
        "/// regd.c `rtw_reg_find_by_name` is not `rtw_reg_ww`.",
        "pub fn rtw_reg_known(alpha2: [u8; 2]) -> bool {",
        "    RTW_REG_MAP.binary_search(&alpha2).is_ok()",
        "}",
        "",
    ]
    open(OUT, "w").write("\n".join(lines))
    print(f"{OUT}: {len(countries)} countries, {len(rtw)} in rtw_reg_map")


if __name__ == "__main__":
    main()
