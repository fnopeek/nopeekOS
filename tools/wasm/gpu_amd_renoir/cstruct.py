#!/usr/bin/env python3
"""Emit a Rust struct mirroring a DC register-table struct, field for field,
with a `from(&[T])` that reads it out of the flat array gen_regs.py writes
into tables.rs for a static of that struct (tables.list).

    python3 cstruct.py HEADER STRUCT [RUST_NAME] [ELEM]

HEADER is relative to drivers/gpu/drm/amd/display/dc. The header is run
through the C preprocessor with its #include lines removed (the field-list
macros live in the header itself), so the field order is the compiler's.
ELEM is the element type of every field (u32 default, u8 for a shift
struct); a field of another width stops the tool, since a flat table of one
element type could not hold it.
"""
import os
import re
import subprocess
import sys
import tempfile

L = os.path.expanduser("~/.cache/nopeekos/amdgpu-callgraph/linux-6.18.55-renoir")
DC = L + "/drivers/gpu/drm/amd/display/dc"
CTYPE = {"u32": "uint32_t", "u8": "uint8_t"}


def fields(header, struct):
    src = "".join(l for l in open(os.path.join(DC, header)) if not l.lstrip().startswith("#include"))
    with tempfile.NamedTemporaryFile("w", suffix=".h", delete=False) as f:
        f.write(src)
        tmp = f.name
    try:
        out = subprocess.run(["gcc", "-E", "-P", tmp], capture_output=True, text=True, check=True).stdout
    finally:
        os.unlink(tmp)
    m = re.search(r"struct\s+%s\s*\{(.*?)\};" % re.escape(struct), out, re.S)
    if not m:
        sys.exit(f"{struct}: not found in {header}")
    names = []
    for decl in m.group(1).split(";"):
        decl = " ".join(decl.split())
        if not decl:
            continue
        dm = re.fullmatch(r"(uint8_t|uint16_t|uint32_t)\s+(\w+)", decl)
        if not dm:
            sys.exit(f"{struct}: cannot read field `{decl}`")
        names.append((dm.group(1), dm.group(2)))
    return names


def main():
    header, struct = sys.argv[1], sys.argv[2]
    rust = sys.argv[3] if len(sys.argv) > 3 else struct
    elem = sys.argv[4] if len(sys.argv) > 4 else "u32"
    fs = fields(header, struct)
    for t, n in fs:
        if t != CTYPE[elem]:
            sys.exit(f"{struct}.{n} is {t}, not {CTYPE[elem]}")
    print(f"/// `struct {struct}` ({header.split('/')[-1]}), generated by cstruct.py.")
    print("#[derive(Default, Clone, Copy, Debug)]")
    print(f"pub struct {rust} {{")
    for _, n in fs:
        print(f"    pub {n}: {elem},")
    print("}")
    print()
    print(f"impl {rust} {{")
    print(f"    pub const LEN: usize = {len(fs)};")
    print()
    print(f"    pub fn from(v: &[{elem}]) -> Self {{")
    print(f"        {rust} {{")
    for i, (_, n) in enumerate(fs):
        print(f"            {n}: v[{i}],")
    print("        }")
    print("    }")
    print("}")


if __name__ == "__main__":
    main()
