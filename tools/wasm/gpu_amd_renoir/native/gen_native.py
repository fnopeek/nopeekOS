#!/usr/bin/env python3
"""Generate src/native_gen.rs: the layouts the guest's Mesa uses for
native contexts on amdgpu, with GCC doing the arithmetic, as gen_regs.py
does for the kernel's headers.

The guest is the one that decides these layouts: Mesa's
`src/virtio/virtio-gpu/drm_hw.h` (the capset, built with libdrm's amdgpu
structs) and `src/amd/common/virtio/amdgpu_virtio_proto.h` (the ccmds,
identical to virglrenderer's copy). Each `NAME = expr` of native.list
becomes a C function returning its value, compiled to assembly, and the
number is read off the `mov $N, %eax` GCC emits; a bare `NAME` is a
constant of those headers, of the virtio-gpu uapi the map info is in, or
of libdrm's amdgpu_internal.h (the fence wait the renderer runs).

    python3 gen_native.py            # rewrite ../src/native_gen.rs
    python3 gen_native.py --check    # fail if it is not what it would write
"""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "native_gen.rs")
LIST = os.path.join(HERE, "native.list")
MESA = os.path.expanduser("~/.cache/nopeekos/gpu-shaders/src/mesa")
LIBDRM = "/usr/include/libdrm"
LIBDRM_SRC = os.path.expanduser("~/.cache/nopeekos/libdrm/libdrm-2.4.134")

PRELUDE = """#include <stddef.h>
#include <stdint.h>
#include <assert.h>
#include <stdalign.h>
#include "drm_hw.h"
#include "amdgpu_virtio_proto.h"
#include <linux/virtio_gpu.h>
#include "amdgpu_internal.h"
"""
FLAGS = ["-O2", "-S", "-DENABLE_DRM_AMDGPU", "-DHAVE_LIBDRM_ATOMIC_PRIMITIVES=1", "-I", LIBDRM,
         "-I", os.path.join(MESA, "src/virtio/virtio-gpu"), "-I", os.path.join(MESA, "src/amd/common/virtio"),
         "-I", os.path.join(MESA, "include"), "-I", os.path.join(LIBDRM_SRC, "amdgpu"), "-I", LIBDRM_SRC,
         "-Wno-padded"]


def values(exprs):
    src = PRELUDE
    for k, e in exprs.items():
        src += f"unsigned long long v_{k}(void);\nunsigned long long v_{k}(void) {{ return {e}; }}\n"
    with tempfile.TemporaryDirectory() as d:
        c = os.path.join(d, "x.c")
        open(c, "w").write(src)
        out = os.path.join(d, "x.s")
        r = subprocess.run(["gcc", *FLAGS, c, "-o", out], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit("gcc failed:\n" + "\n".join(r.stderr.splitlines()[:30]))
        asm = open(out).read()
    res, cur = {}, None
    for line in asm.splitlines():
        m = re.match(r"^v_(\w+):", line)
        if m:
            cur = m.group(1)
            continue
        if cur is None:
            continue
        m = re.match(r"\s+mov(l|q|absq)\s+\$(-?\d+), %[er]ax", line)
        if m:
            width = 0xFFFF_FFFF if m.group(1) == "l" else 0xFFFF_FFFF_FFFF_FFFF
            res[cur] = int(m.group(2)) & width
        elif re.match(r"\s+xorl\s+%eax, %eax", line):
            res[cur] = 0
        elif re.match(r"\s+ret", line):
            cur = None
    missing = set(exprs) - set(res)
    if missing:
        sys.exit(f"no constant from GCC for: {sorted(missing)}")
    return res


def main():
    check = "--check" in sys.argv
    items, groups = [], []
    for line in open(LIST):
        line = line.rstrip("\n")
        if not line.strip():
            continue
        if line.startswith("# "):
            items.append(("#", line[2:]))
            continue
        if "=" in line:
            name, expr = (x.strip() for x in line.split("=", 1))
        else:
            name = expr = line.strip()
        items.append((name, expr))
    vals = values({n: e for n, e in items if n != "#"})
    out = ["//! Generated by native/gen_native.py from native.list: the layouts",
           "//! of Mesa's drm_hw.h and amdgpu_virtio_proto.h (with libdrm's amdgpu",
           "//! structs) as the guest builds them; do not edit.", "#![allow(dead_code)]", ""]
    for name, expr in items:
        if name == "#":
            out.append(f"// {expr}")
            continue
        v = vals[name]
        ty = "u32" if v <= 0xFFFF_FFFF else "u64"
        if expr != name:
            out.append(f"/// `{expr}`")
        out.append(f"pub const {name}: {ty} = {v:#x};")
    text = "\n".join(out) + "\n"
    if check:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("gen_native: src/native_gen.rs is not what it would write")
        return
    open(OUT, "w").write(text)
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
