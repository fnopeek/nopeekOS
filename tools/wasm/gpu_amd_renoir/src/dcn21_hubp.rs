//! display/dc/inc/hw/hubp.h + hubp/dcn{10,20,21}_hubp.{h,c} (Linux 6.18.55),
//! with the `hubp_regs`/`hubp_shift`/`hubp_mask` table of dcn21_resource.c: the
//! hub pixel fetcher (HUBP) of Renoir's resource pool. One per pipe, and the
//! biggest register block.
//!
//! `dcn21_hubp_create` → `hubp21_construct` stores the instance, the funcs
//! and the register pointers (and the invalid opp/mpcc ids). The ops of
//! dcn10/20/21_hubp.c are ported as the hw sequencer reaches them. The three
//! register structs below and the
//! `HUBP_REGS`/`HUBP_SHIFT`/`HUBP_MASK` tables are machine-generated by
//! `dcgen.py` from Linux' `HUBP_REG_LIST_DCN21` / `HUBP_MASK_SH_LIST_DCN21`
//! macros (expanded with the C preprocessor), so the 111 registers x 4 pipes
//! and 191 fields are Linux' own, not transcribed. Shift/mask fields a C
//! designated initializer would set twice keep the last macro, as C does.
