//! display/dc/inc/hw/hubp.h + hubp/dcn{10,20,21}_hubp.{h,c} (Linux 6.18.55),
//! with the `hubp_regs`/`hubp_shift`/`hubp_mask` table of dcn21_resource.c: the
//! hub pixel fetcher (HUBP) of Renoir's resource pool. One per pipe, and the
//! biggest register block.
//!
//! `dcn21_hubp_create` → `hubp21_construct` stores the instance, the funcs
//! identity and the register pointers (and the invalid opp/mpcc ids); it writes
//! no register — the HUBP programming (viewport, surface address, flip, dlg/ttu
//! watermarks) is hwss-stage. The three register structs below and the
//! `HUBP_REGS`/`HUBP_SHIFT`/`HUBP_MASK` tables are machine-generated by
//! `dcgen.py` from Linux' `HUBP_REG_LIST_DCN21` / `HUBP_MASK_SH_LIST_DCN21`
//! macros (expanded with the C preprocessor), so the 111 registers x 4 pipes
//! and 191 fields are Linux' own, not transcribed. Shift/mask fields a C
//! designated initializer would set twice keep the last macro, as C does.
#![allow(dead_code)]

use crate::regs::*;
use alloc::boxed::Box;

/// `#define OPP_ID_INVALID` (inc/hw/hubp.h).
const OPP_ID_INVALID: i32 = 0xf;

/// Which `hubp_funcs` vtable `hubp.funcs` points at (dcn21_hubp.c). Only the
/// identity is carried; the ops are hwss-stage.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum hubp_funcs {
    dcn21_hubp_funcs,
}

/// `struct hubp` (inc/hw/hubp.h): the base object. Linux' `ctx` is not stored
/// (see `clock_source`); the cursor/plane run-time state joins with a funcs op
/// that uses it.
#[derive(Default)]
pub struct hubp {
    pub funcs: Option<hubp_funcs>,
    pub inst: u32,
    pub opp_id: i32,
    pub mpcc_id: i32,
}

/// `struct dcn21_hubp` (dcn21_hubp.h): the concrete HUBP. `state`,
/// `PLAT_54186_wa_chroma_addr_offset` join grow-as-reached.
#[derive(Default)]
pub struct dcn21_hubp {
    pub base: hubp,
    pub hubp_regs: Option<&'static dcn_hubp2_registers>,
    pub hubp_shift: Option<&'static dcn_hubp2_shift>,
    pub hubp_mask: Option<&'static dcn_hubp2_mask>,
}

/// `hubp21_construct` (dcn21_hubp.c): store the instance, funcs and registers;
/// set the opp/mpcc ids to invalid. Always succeeds here (Linux' body cannot
/// fail; the NULL path is the kzalloc in the create).
pub fn hubp21_construct(
    hubp21: &mut dcn21_hubp,
    inst: u32,
    hubp_regs: &'static dcn_hubp2_registers,
    hubp_shift: &'static dcn_hubp2_shift,
    hubp_mask: &'static dcn_hubp2_mask,
) -> bool {
    hubp21.base.funcs = Some(hubp_funcs::dcn21_hubp_funcs);
    hubp21.hubp_regs = Some(hubp_regs);
    hubp21.hubp_shift = Some(hubp_shift);
    hubp21.hubp_mask = Some(hubp_mask);
    hubp21.base.inst = inst;
    hubp21.base.opp_id = OPP_ID_INVALID;
    hubp21.base.mpcc_id = 0xf;
    true
}

/// `dcn21_hubp_create` (dcn21_resource.c): allocate a `dcn21_hubp` for pipe
/// `inst` and construct it.
pub fn dcn21_hubp_create(inst: u32) -> Option<Box<dcn21_hubp>> {
    let mut hubp21 = Box::new(dcn21_hubp::default());
    if hubp21_construct(&mut hubp21, inst, &HUBP_REGS[inst as usize], &HUBP_SHIFT, &HUBP_MASK) {
        Some(hubp21)
    } else {
        None
    }
}

