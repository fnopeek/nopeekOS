/// `log_2` (basics/conversion.h): the kernel's run-time `ilog2`,
/// `fls(n) - 1`, which is -1 for 0.
fn log_2(num: u32) -> u32 {
    (32 - num.leading_zeros()).wrapping_sub(1)
}

