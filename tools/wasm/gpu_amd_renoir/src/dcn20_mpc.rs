/// `dcn20_mpc_construct` (dcn20_mpc.c): store the funcs and registers, reset the
/// use mask and node count, and init the mixing nodes.
pub fn dcn20_mpc_construct(
    mpc20: &mut dcn20_mpc,
    mpc_regs: &'static dcn20_mpc_registers,
    mpc_shift: &'static dcn20_mpc_shift,
    mpc_mask: &'static dcn20_mpc_mask,
    num_mpcc: i32,
) {
    mpc20.base.funcs = Some(mpc_funcs::dcn20_mpc_funcs);
    mpc20.mpc_regs = Some(mpc_regs);
    mpc20.mpc_shift = Some(mpc_shift);
    mpc20.mpc_mask = Some(mpc_mask);
    mpc20.mpcc_in_use_mask = 0;
    mpc20.num_mpcc = num_mpcc;

    for i in 0..MAX_MPCC {
        mpc2_init_mpcc(&mut mpc20.base.mpcc_array[i], i as i32);
    }
}

