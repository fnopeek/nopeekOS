//! display/dc/inc/hw/mpc.h + mpc/dcn20/dcn20_mpc.{h,c} (Linux 6.18.55), with the
//! `mpc_regs`/`mpc_shift`/`mpc_mask` table of dcn21_resource.c: the multiple pipe
//! and plane combiner (MPC) of Renoir's resource pool. Renoir reuses the dcn20
//! MPC. There is one MPC for the device, with `MAX_MPCC` mixing nodes.
//!
//! `dcn21_mpc_create` → `dcn20_mpc_construct` stores the funcs and the
//! register pointers and initialises the `mpcc_array` blending nodes. The ops
//! of dcn10/20_mpc.c are ported as the hw sequencer reaches them. The register
//! struct is a single struct with per-MPCC array fields (`SRII` into `.F[inst]`),
//! machine-generated by `dcgen.py` (single mode) from `MPC_REG_LIST_DCN2_0` x6 +
//! `MPC_OUT_MUX_REG_LIST_DCN2_0` x4 + the debug list, and
//! `MPC_COMMON_MASK_SH_LIST_DCN2_0`.
#![allow(dead_code)]

use crate::amdgpu_device::amdgpu_device;
use crate::dc_helper::{reg_get, reg_set, reg_update, reg_wait};
use crate::regs::*;
use alloc::boxed::Box;

/// `#define MAX_MPCC` (inc/hw/mpc.h).
pub const MAX_MPCC: usize = 6;

/// `#define MAX_OPP` (inc/hw/opp.h).
pub const MAX_OPP: usize = 6;

/// Which `mpc_funcs` vtable `mpc.funcs` points at (dcn20_mpc.c).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum mpc_funcs {
    dcn20_mpc_funcs,
}

/// `struct mpc_funcs` (mpc.h), the members ported. `None` is a member the
/// port has not reached.
#[derive(Default, Clone, Copy)]
pub struct mpc_ops {
    pub mpc_init_single_inst: Option<fn(&amdgpu_device, &mut dcn20_mpc, u32)>,
    pub get_mpcc_for_dpp: Option<fn(&dcn20_mpc, &mpc_tree, i32) -> Option<usize>>,
    pub wait_for_idle: Option<fn(&amdgpu_device, &dcn20_mpc, i32)>,
}

/// `dcn20_mpc_funcs` (dcn20_mpc.c), as far as ported.
const DCN20_MPC_FUNCS: mpc_ops = mpc_ops {
    mpc_init_single_inst: Some(mpc1_mpc_init_single_inst),
    get_mpcc_for_dpp: Some(mpc2_get_mpcc_for_dpp),
    wait_for_idle: Some(mpc2_assert_idle_mpcc),
};

impl mpc_funcs {
    pub fn ops(self) -> &'static mpc_ops {
        match self {
            mpc_funcs::dcn20_mpc_funcs => &DCN20_MPC_FUNCS,
        }
    }
}

/// `struct mpc_tree` (inc/hw/mpc.h): an OPP's blending tree. `opp_list` is
/// the index of its top node in `mpc.mpcc_array`.
#[derive(Default, Clone, Copy)]
pub struct mpc_tree {
    pub opp_id: i32,
    pub opp_list: Option<usize>,
}

/// `struct mpcc_blnd_cfg` (inc/hw/mpc.h): ported grow-as-reached — the fields
/// `mpc2_init_mpcc` sets. `background_color` and the CM fields join with a
/// blending op that uses them.
#[derive(Default, Clone, Copy)]
pub struct mpcc_blnd_cfg {
    pub global_gain: i32,
    pub global_alpha: i32,
    pub overlap_only: bool,
    pub bottom_gain_mode: i32,
    pub background_color_bpc: i32,
    pub top_gain: i32,
    pub bottom_inside_gain: i32,
    pub bottom_outside_gain: i32,
}

/// `struct mpcc_sm_cfg` (inc/hw/mpc.h): stereo-mix config (grow-as-reached).
#[derive(Default, Clone, Copy)]
pub struct mpcc_sm_cfg {
    pub enable: bool,
}

/// `struct mpcc` (inc/hw/mpc.h): one MPC mixing node. Linux' `mpcc_bot` is a
/// pointer to the bottom node; the port carries the bottom node's array index
/// (None when unconnected, as at init), since the chain is built hwss-side.
#[derive(Default, Clone, Copy)]
pub struct mpcc {
    pub mpcc_id: i32,
    pub dpp_id: i32,
    pub mpcc_bot: Option<usize>,
    pub blnd_cfg: mpcc_blnd_cfg,
    pub sm_cfg: mpcc_sm_cfg,
    pub shared_bottom: bool,
}

/// `struct mpc` (inc/hw/mpc.h): the base object. Linux' `ctx` is not stored (see
/// `clock_source`).
#[derive(Default)]
pub struct mpc {
    pub funcs: Option<mpc_funcs>,
    pub mpcc_array: [mpcc; MAX_MPCC],
}

/// `struct dcn20_mpc` (dcn20_mpc.h): the concrete MPC.
#[derive(Default)]
pub struct dcn20_mpc {
    pub base: mpc,
    pub mpcc_in_use_mask: i32,
    pub num_mpcc: i32,
    pub mpc_regs: Option<&'static dcn20_mpc_registers>,
    pub mpc_shift: Option<&'static dcn20_mpc_shift>,
    pub mpc_mask: Option<&'static dcn20_mpc_mask>,
}

impl dcn20_mpc {
    /// `mpc->funcs`.
    pub fn funcs(&self) -> &'static mpc_ops {
        self.base.funcs.expect("mpc funcs").ops()
    }

    fn rsm(&self) -> (&'static dcn20_mpc_registers, &'static dcn20_mpc_shift, &'static dcn20_mpc_mask) {
        (self.mpc_regs.unwrap(), self.mpc_shift.unwrap(), self.mpc_mask.unwrap())
    }
}

/// `mpc1_init_mpcc` (dcn10_mpc.c).
fn mpc1_init_mpcc(m: &mut mpcc, mpcc_inst: i32) {
    m.mpcc_id = mpcc_inst;
    m.dpp_id = 0xf;
    m.mpcc_bot = None;
    m.blnd_cfg.overlap_only = false;
    m.blnd_cfg.global_alpha = 0xff;
    m.blnd_cfg.global_gain = 0xff;
    m.sm_cfg.enable = false;
}

/// `mpc1_mpc_init_single_inst` (dcn10_mpc.c): disconnect one mixing node and
/// the output mux of the OPP it fed. `MUX` has MAX_OPP entries in Linux; the
/// ones past the generated table are 0 there, so they are skipped here too.
pub fn mpc1_mpc_init_single_inst(adev: &amdgpu_device, mpc10: &mut dcn20_mpc, mpcc_id: u32) {
    let i = mpcc_id as usize;
    let opp_id = reg_get!(adev, mpc10.rsm(), MPCC_OPP_ID[i], MPCC_OPP_ID) as i32;

    reg_set!(adev, mpc10.rsm(), MPCC_TOP_SEL[i], 0, MPCC_TOP_SEL, 0xf);
    reg_set!(adev, mpc10.rsm(), MPCC_BOT_SEL[i], 0, MPCC_BOT_SEL, 0xf);
    reg_set!(adev, mpc10.rsm(), MPCC_OPP_ID[i], 0, MPCC_OPP_ID, 0xf);
    reg_set!(adev, mpc10.rsm(), MPCC_UPDATE_LOCK_SEL[i], 0, MPCC_UPDATE_LOCK_SEL, 0xf);

    mpc1_init_mpcc(&mut mpc10.base.mpcc_array[i], mpcc_id as i32);

    let regs = mpc10.rsm().0;
    if opp_id < MAX_OPP as i32 && regs.MUX.get(opp_id as usize).is_some_and(|&r| r != 0) {
        reg_update!(adev, mpc10.rsm(), MUX[opp_id as usize], MPC_OUT_MUX, 0xf);
    }
}

/// `mpc2_get_mpcc_for_dpp` (dcn20_mpc.c): the node of `tree` that blends
/// `dpp_id`, or the first free one.
pub fn mpc2_get_mpcc_for_dpp(mpc: &dcn20_mpc, tree: &mpc_tree, dpp_id: i32) -> Option<usize> {
    let mut tmp_mpcc = tree.opp_list;

    while let Some(t) = tmp_mpcc {
        let m = &mpc.base.mpcc_array[t];
        if m.dpp_id == 0xf || m.dpp_id == dpp_id {
            return Some(t);
        }

        // avoid circular linked list
        if Some(t) == m.mpcc_bot {
            break;
        }

        tmp_mpcc = m.mpcc_bot;
    }
    None
}

/// `mpc2_assert_idle_mpcc` (dcn20_mpc.c).
pub fn mpc2_assert_idle_mpcc(adev: &amdgpu_device, mpc20: &dcn20_mpc, id: i32) {
    let i = id as usize;
    let mpc_disabled = reg_get!(adev, mpc20.rsm(), MPCC_STATUS[i], MPCC_DISABLED);
    if mpc_disabled != 0 {
        return;
    }

    reg_wait!(adev, mpc20.rsm(), MPCC_STATUS[i], MPCC_IDLE, 1, 1, 100000, "mpc2_assert_idle_mpcc");
}

/// `mpc2_init_mpcc` (dcn20_mpc.c): the reset state of one mixing node.
fn mpc2_init_mpcc(m: &mut mpcc, mpcc_inst: i32) {
    m.mpcc_id = mpcc_inst;
    m.dpp_id = 0xf;
    m.mpcc_bot = None;
    m.blnd_cfg.overlap_only = false;
    m.blnd_cfg.global_alpha = 0xff;
    m.blnd_cfg.global_gain = 0xff;
    m.blnd_cfg.background_color_bpc = 4;
    m.blnd_cfg.bottom_gain_mode = 0;
    m.blnd_cfg.top_gain = 0x1f000;
    m.blnd_cfg.bottom_inside_gain = 0x1f000;
    m.blnd_cfg.bottom_outside_gain = 0x1f000;
    m.sm_cfg.enable = false;
}

/// `dcn20_mpc_construct` (dcn20_mpc.c): store the funcs and registers, reset the
/// use mask and node count, and init the mixing nodes.
pub fn dcn20_mpc_construct(
    mpc20: &mut dcn20_mpc,
    mpc_regs: &'static dcn20_mpc_registers,
    mpc_shift: &'static dcn20_mpc_shift,
    mpc_mask: &'static dcn20_mpc_mask,
    num_mpcc: i32,
) {
    mpc20.base.funcs = Some(mpc_funcs::dcn20_mpc_funcs);
    mpc20.mpc_regs = Some(mpc_regs);
    mpc20.mpc_shift = Some(mpc_shift);
    mpc20.mpc_mask = Some(mpc_mask);
    mpc20.mpcc_in_use_mask = 0;
    mpc20.num_mpcc = num_mpcc;

    for i in 0..MAX_MPCC {
        mpc2_init_mpcc(&mut mpc20.base.mpcc_array[i], i as i32);
    }
}

/// `dcn21_mpc_create` (dcn21_resource.c): allocate the MPC and construct it with
/// `MAX_MPCC` (6) mixing nodes.
pub fn dcn21_mpc_create() -> Box<dcn20_mpc> {
    let mut mpc20 = Box::new(dcn20_mpc::default());
    dcn20_mpc_construct(&mut mpc20, &MPC_REGS, &MPC_SHIFT, &MPC_MASK, 6);
    mpc20
}

