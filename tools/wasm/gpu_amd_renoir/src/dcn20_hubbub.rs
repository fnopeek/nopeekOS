//! display/dc/inc/hw/dchubbub.h + inc/hw/vmid.h + hubbub/dcn{10,20,21}_hubbub.c
//! + dcn20/dcn20_vmid (Linux 6.18.55), with the `hubbub_reg`/`vmid_regs` tables
//! of dcn21_resource.c: the hub bottleneck arbiter (HUBBUB) of Renoir's resource
//! pool, and its per-VMID register banks. One HUBBUB for the device.
//!
//! `dcn21_hubbub_create` → `hubbub21_construct` stores the funcs identity and the
//! register pointers and the detile buffer size, then the create fills the 16
//! VMID banks. The ops of dcn10/20/21_hubbub.c are ported as the hw sequencer
//! reaches them. Two tables, both machine-generated by `dcgen.py`: the HUBBUB
//! registers as a single struct (`HUBBUB_REG_LIST_DCN21` /
//! `HUBBUB_MASK_SH_LIST_DCN21`), and the VMID registers as an array of 16
//! (`DCN20_VMID_REG_LIST` / `DCN20_VMID_MASK_SH_LIST`).
#![allow(dead_code)]

use crate::amdgpu_device::amdgpu_device;
use crate::dc_helper::{reg_get, reg_get_n, reg_set, reg_update, reg_wait};
use crate::regs::*;
use alloc::boxed::Box;

/// Which `hubbub_funcs` vtable `hubbub.funcs` points at (dcn21_hubbub.c).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum hubbub_funcs {
    hubbub21_funcs,
}

/// `struct hubbub_funcs` (dchubbub.h), the members ported. The `None`
/// members of `HUBBUB21_FUNCS` are members hubbub21 leaves out.
#[derive(Default, Clone, Copy)]
pub struct hubbub_ops {
    pub get_dchub_ref_freq: Option<fn(&amdgpu_device, &dcn20_hubbub, u32, &mut u32)>,
    pub allow_self_refresh_control: Option<fn(&amdgpu_device, &dcn20_hubbub, bool)>,
    pub is_allow_self_refresh_enabled: Option<fn(&amdgpu_device, &dcn20_hubbub) -> bool>,
    pub verify_allow_pstate_change_high: Option<fn(&amdgpu_device, &dcn20_hubbub) -> bool>,
    pub program_det_size: Option<fn(&amdgpu_device, &dcn20_hubbub, u32, u32)>,
    pub program_det_segments: Option<fn(&amdgpu_device, &dcn20_hubbub, u32, u32)>,
    pub init_dchub_sys_ctx: Option<fn(&amdgpu_device, &crate::dc::dc_config, &mut dcn20_hubbub,
                                      &dcn_hubbub_phys_addr_config) -> i32>,
}

/// `hubbub21_funcs` (dcn21_hubbub.c), as far as ported.
const HUBBUB21_FUNCS: hubbub_ops = hubbub_ops {
    get_dchub_ref_freq: Some(hubbub2_get_dchub_ref_freq),
    allow_self_refresh_control: Some(hubbub1_allow_self_refresh_control),
    is_allow_self_refresh_enabled: None,
    verify_allow_pstate_change_high: None,
    program_det_size: None,
    program_det_segments: None,
    init_dchub_sys_ctx: Some(hubbub21_init_dchub),
};

impl hubbub_funcs {
    pub fn ops(self) -> &'static hubbub_ops {
        match self {
            hubbub_funcs::hubbub21_funcs => &HUBBUB21_FUNCS,
        }
    }
}

/// `struct hubbub` (inc/hw/dchubbub.h): the base object. Linux' `ctx` is not
/// stored (see `clock_source`).
#[derive(Default)]
pub struct hubbub {
    pub funcs: Option<hubbub_funcs>,
    pub riommu_active: bool,
}

/// `struct dcn20_vmid` (dcn20/dcn20_vmid.h): one VMID's register bank. `ctx` is
/// not stored.
#[derive(Default, Clone, Copy)]
pub struct dcn20_vmid {
    pub regs: Option<&'static dcn_vmid_registers>,
    pub shifts: Option<&'static dcn20_vmid_shift>,
    pub masks: Option<&'static dcn20_vmid_mask>,
}

/// `struct dcn20_hubbub` (dcn20_hubbub.h): the concrete HUBBUB. The watermark
/// set and the DET/CRB sizing fields join grow-as-reached.
#[derive(Default)]
pub struct dcn20_hubbub {
    pub base: hubbub,
    pub regs: Option<&'static dcn_hubbub_registers>,
    pub shifts: Option<&'static dcn_hubbub_shift>,
    pub masks: Option<&'static dcn_hubbub_mask>,
    pub debug_test_index_pstate: u32,
    pub num_vmid: i32,
    pub vmid: [dcn20_vmid; 16],
    pub detile_buf_size: u32,
}

impl dcn20_hubbub {
    /// `hubbub->funcs`.
    pub fn funcs(&self) -> &'static hubbub_ops {
        self.base.funcs.expect("hubbub funcs").ops()
    }

    fn rsm(&self) -> (&'static dcn_hubbub_registers, &'static dcn_hubbub_shift, &'static dcn_hubbub_mask) {
        (self.regs.unwrap(), self.shifts.unwrap(), self.masks.unwrap())
    }
}

/// `hubbub2_get_dchub_ref_freq` (dcn20_hubbub.c). The DC hub reference must
/// be around 50 MHz, and the global timer enabled; Linux asserts both.
pub fn hubbub2_get_dchub_ref_freq(adev: &amdgpu_device, hubbub1: &dcn20_hubbub, dccg_ref_freq_inKhz: u32,
                                  dchub_ref_freq_inKhz: &mut u32) {
    let [ref_div, ref_en] = reg_get_n!(adev, hubbub1.rsm(), DCHUBBUB_GLOBAL_TIMER_CNTL,
        DCHUBBUB_GLOBAL_TIMER_REFDIV, DCHUBBUB_GLOBAL_TIMER_ENABLE);

    if ref_en != 0 {
        if ref_div == 2 {
            *dchub_ref_freq_inKhz = dccg_ref_freq_inKhz / 2;
        } else {
            *dchub_ref_freq_inKhz = dccg_ref_freq_inKhz;
        }
    } else {
        *dchub_ref_freq_inKhz = dccg_ref_freq_inKhz;
    }
}

/// `hubbub1_allow_self_refresh_control` (dcn10_hubbub.c): FORCE_ENABLE = 1
/// means do not allow stutter, 0 means allow it.
pub fn hubbub1_allow_self_refresh_control(adev: &amdgpu_device, hubbub1: &dcn20_hubbub, allow: bool) {
    reg_update!(adev, hubbub1.rsm(), DCHUBBUB_ARB_DRAM_STATE_CNTL,
        DCHUBBUB_ARB_ALLOW_SELF_REFRESH_FORCE_VALUE, 0,
        DCHUBBUB_ARB_ALLOW_SELF_REFRESH_FORCE_ENABLE, !allow as u32);
}

