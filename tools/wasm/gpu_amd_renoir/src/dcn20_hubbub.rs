//! display/dc/inc/hw/dchubbub.h + inc/hw/vmid.h + hubbub/dcn{10,20,21}_hubbub.c
//! + dcn20/dcn20_vmid (Linux 6.18.55), with the `hubbub_reg`/`vmid_regs` tables
//! of dcn21_resource.c: the hub bottleneck arbiter (HUBBUB) of Renoir's resource
//! pool, and its per-VMID register banks. One HUBBUB for the device.
//!
//! `dcn21_hubbub_create` → `hubbub21_construct` stores the funcs identity and the
//! register pointers and the detile buffer size, then the create fills the 16
//! VMID banks. It writes no register (the arbiter/watermark programming is
//! hwss-stage). Two tables, both machine-generated by `dcgen.py`: the HUBBUB
//! registers as a single struct (`HUBBUB_REG_LIST_DCN21` /
//! `HUBBUB_MASK_SH_LIST_DCN21`), and the VMID registers as an array of 16
//! (`DCN20_VMID_REG_LIST` / `DCN20_VMID_MASK_SH_LIST`).
#![allow(dead_code)]

use crate::regs::*;
use alloc::boxed::Box;

/// Which `hubbub_funcs` vtable `hubbub.funcs` points at (dcn21_hubbub.c).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum hubbub_funcs {
    hubbub21_funcs,
}

/// `struct hubbub` (inc/hw/dchubbub.h): the base object. Linux' `ctx` is not
/// stored (see `clock_source`).
#[derive(Default)]
pub struct hubbub {
    pub funcs: Option<hubbub_funcs>,
}

/// `struct dcn20_vmid` (dcn20/dcn20_vmid.h): one VMID's register bank. `ctx` is
/// not stored.
#[derive(Default, Clone, Copy)]
pub struct dcn20_vmid {
    pub regs: Option<&'static dcn_vmid_registers>,
    pub shifts: Option<&'static dcn20_vmid_shift>,
    pub masks: Option<&'static dcn20_vmid_mask>,
}

/// `struct dcn20_hubbub` (dcn20_hubbub.h): the concrete HUBBUB. The watermark
/// set and the DET/CRB sizing fields join grow-as-reached.
#[derive(Default)]
pub struct dcn20_hubbub {
    pub base: hubbub,
    pub regs: Option<&'static dcn_hubbub_registers>,
    pub shifts: Option<&'static dcn_hubbub_shift>,
    pub masks: Option<&'static dcn_hubbub_mask>,
    pub debug_test_index_pstate: u32,
    pub num_vmid: i32,
    pub vmid: [dcn20_vmid; 16],
    pub detile_buf_size: u32,
}

/// `hubbub21_construct` (dcn21_hubbub.c): store the funcs, registers and the
/// detile buffer size.
pub fn hubbub21_construct(
    hubbub: &mut dcn20_hubbub,
    hubbub_regs: &'static dcn_hubbub_registers,
    hubbub_shift: &'static dcn_hubbub_shift,
    hubbub_mask: &'static dcn_hubbub_mask,
) {
    hubbub.base.funcs = Some(hubbub_funcs::hubbub21_funcs);
    hubbub.regs = Some(hubbub_regs);
    hubbub.shifts = Some(hubbub_shift);
    hubbub.masks = Some(hubbub_mask);
    hubbub.debug_test_index_pstate = 0xB;
    hubbub.detile_buf_size = 164 * 1024; // 164KB for DCN2.0
}

/// `dcn21_hubbub_create` (dcn21_resource.c): construct the HUBBUB and point each
/// of the `res_cap_rn.num_vmid` (16) VMID banks at its registers.
pub fn dcn21_hubbub_create() -> Box<dcn20_hubbub> {
    let mut hubbub = Box::new(dcn20_hubbub::default());
    hubbub21_construct(&mut hubbub, &HUBBUB_REGS, &HUBBUB_SHIFT, &HUBBUB_MASK);

    for i in 0..16 {
        let vmid = &mut hubbub.vmid[i];
        vmid.regs = Some(&VMID_REGS[i]);
        vmid.shifts = Some(&VMID_SHIFT);
        vmid.masks = Some(&VMID_MASK);
    }
    hubbub.num_vmid = 16;
    hubbub
}

