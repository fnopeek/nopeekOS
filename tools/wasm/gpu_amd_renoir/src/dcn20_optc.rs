//! display/dc/inc/hw/timing_generator.h + inc/hw/optc.h + optc/dcn20/dcn20_optc.c
//! (Linux 6.18.55), with the `tg_regs`/`tg_shift`/`tg_mask` table of
//! dcn21_resource.c: the optc / timing generator (OTG) of Renoir's resource
//! pool. Renoir reuses the dcn20 OTG. The last per-pipe block.
//!
//! `dcn21_timing_generator_create` sets the instance and register pointers, then
//! `dcn20_timing_generator_init` installs the funcs identity and derives the
//! max/min timing limits from the mask (`max_h_total = tg_mask->OTG_H_TOTAL + 1`,
//! …). It writes no register (the OTG programming — timing, vblank, locking — is
//! hwss-stage). The register tables are machine-generated by `dcgen.py` from
//! `TG_COMMON_REG_LIST_DCN2_0` / `TG_COMMON_MASK_SH_LIST_DCN2_0`.
#![allow(dead_code)]

use crate::regs::*;
use alloc::boxed::Box;

/// Which `timing_generator_funcs` vtable the base points at (dcn20_optc.c).
/// Identity only; the ops are hwss-stage.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum timing_generator_funcs {
    dcn20_tg_funcs,
}

/// `struct timing_generator` (inc/hw/timing_generator.h): the base object. Linux'
/// `bp`/`ctx` are not stored (see `clock_source`).
#[derive(Default)]
pub struct timing_generator {
    pub funcs: Option<timing_generator_funcs>,
    pub inst: u32,
}

/// `struct optc` (inc/hw/optc.h): the concrete timing generator. The remaining
/// run-time fields (vupdate/vready offsets, pstate state, …) join grow-as-reached.
#[derive(Default)]
pub struct optc {
    pub base: timing_generator,
    pub tg_regs: Option<&'static dcn_optc_registers>,
    pub tg_shift: Option<&'static dcn_optc_shift>,
    pub tg_mask: Option<&'static dcn_optc_mask>,
    pub max_h_total: u32,
    pub max_v_total: u32,
    pub min_h_blank: u32,
    pub min_h_sync_width: u32,
    pub min_v_sync_width: u32,
    pub min_v_blank: u32,
    pub min_v_blank_interlace: u32,
}

/// `dcn20_timing_generator_init` (dcn20_optc.c): install the funcs table and
/// derive the timing limits from the mask.
pub fn dcn20_timing_generator_init(optc1: &mut optc) {
    optc1.base.funcs = Some(timing_generator_funcs::dcn20_tg_funcs);

    let mask = optc1.tg_mask.unwrap();
    optc1.max_h_total = mask.OTG_H_TOTAL + 1;
    optc1.max_v_total = mask.OTG_V_TOTAL + 1;

    optc1.min_h_blank = 32;
    optc1.min_v_blank = 3;
    optc1.min_v_blank_interlace = 5;
    optc1.min_h_sync_width = 4;
    optc1.min_v_sync_width = 1;
}

/// `dcn21_timing_generator_create` (dcn21_resource.c): allocate an `optc` for
/// pipe `instance`, point it at its registers, and init it.
pub fn dcn21_timing_generator_create(instance: u32) -> Box<optc> {
    let mut tgn10 = Box::new(optc::default());
    tgn10.base.inst = instance;
    tgn10.tg_regs = Some(&OPTC_REGS[instance as usize]);
    tgn10.tg_shift = Some(&OPTC_SHIFT);
    tgn10.tg_mask = Some(&OPTC_MASK);
    dcn20_timing_generator_init(&mut tgn10);
    tgn10
}

