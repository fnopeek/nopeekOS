def dump_closure(w):
    seen = []

    def visit(name):
        if name in seen:
            return
        seen.append(name)
        for f, fq, bf in w.records[name]:
            t = w.resolve(parse_type(fq))
            while t[0] == "arr":
                t = w.resolve(t[1])
            if t[0] == "struct":
                visit(t[1])

    for n in DUMP_STRUCTS:
        visit(n)
    return seen


def emit_dump_c(w):
    """Every nonzero leaf as `path value`; floating point by its bits."""
    out = ["/* Generated by dmlgen.py; do not edit. The DML structs as text, nonzero leaves only, in the", " * format hostcheck/dml_dump.rs prints. */", ""]
    names = dump_closure(w)
    cn = lambda n: w.c_name.get(n) or "struct " + n
    for n in names:
        out.append("static void dmldump_%s(const char *p, const %s *v);" % (n, cn(n)))
    out.append("")
    for n in names:
        out.append("static void dmldump_%s(const char *p, const %s *v)" % (n, cn(n)))
        out.append("{")
        out.append("\tchar q[512];")
        out.append("\t(void)q;")
        for f, fq, bf in w.records[n]:
            t = w.resolve(parse_type(fq))
            dims = []
            while t[0] == "arr":
                dims.append(t[2])
                t = w.resolve(t[1])
            idx = "".join("[i%d]" % d for d in range(len(dims)))
            pad = "\t"
            for d, nn in enumerate(dims):
                out.append(pad + "for (int i%d = 0; i%d < %d; i%d++)" % (d, d, nn, d))
                pad += "\t"
            fmt_idx = "".join("[%d]" for _ in dims)
            args_idx = "".join(", i%d" % d for d in range(len(dims)))
            ref = "v->%s%s" % (f, idx)
            if t[0] == "struct":
                out.append(pad + "{ snprintf(q, sizeof(q), \"%%s.%s%s\", p%s); dmldump_%s(q, &%s); }" % (
                    f, fmt_idx, args_idx, t[1], ref))
            elif t[0] in ("fnptr", "ptr"):
                continue
            elif t[0] == "prim" and t[1] == "f64":
                out.append(pad + "{ double d = %s; unsigned long long b; memcpy(&b, &d, 8); if (b) printf(\"%%s.%s%s %%016llx\\n\", p%s, b); }" % (
                    ref, f, fmt_idx, args_idx))
            elif t[0] == "prim" and t[1] == "f32":
                out.append(pad + "{ float d = %s; unsigned int b; memcpy(&b, &d, 4); if (b) printf(\"%%s.%s%s %%08x\\n\", p%s, b); }" % (
                    ref, f, fmt_idx, args_idx))
            else:
                out.append(pad + "if (%s) printf(\"%%s.%s%s %%lld\\n\", p%s, (long long)%s);" % (ref, f, fmt_idx, args_idx, ref))
        out.append("}")
        out.append("")
    return out


def emit_dump_rs(w):
    out = ["//! Generated by dmlgen.py; do not edit. The DML structs as text, nonzero leaves only, in",
           "//! the format oracle/dml_dump.h prints.", "#![allow(non_snake_case, unused_variables)]", "",
           "use crate::display_mode_structs::*;", ""]
    for n in dump_closure(w):
        out.append("pub fn dmldump_%s(p: &str, v: &%s) {" % (n, n))
        for f, fq, bf in w.records[n]:
            t = w.resolve(parse_type(fq))
            dims = []
            while t[0] == "arr":
                dims.append(t[2])
                t = w.resolve(t[1])
            if t[0] in ("fnptr", "ptr"):
                continue
            pad = "    "
            for d, nn in enumerate(dims):
                out.append(pad + "for i%d in 0..%d {" % (d, nn))
                pad += "    "
            ref = "v.%s%s" % (rname(f), "".join("[i%d]" % d for d in range(len(dims))))
            path = "format!(\"{}.%s%s\", p%s)" % (f, "".join("[{}]" for _ in dims), "".join(", i%d" % d for d in range(len(dims))))
            if t[0] == "struct":
                out.append(pad + "dmldump_%s(&%s, &%s);" % (t[1], path, ref))
            elif t[0] == "prim" and t[1] == "f64":
                out.append(pad + "if %s.to_bits() != 0 { println!(\"{} {:016x}\", %s, %s.to_bits()); }" % (ref, path, ref))
            elif t[0] == "prim" and t[1] == "f32":
                out.append(pad + "if %s.to_bits() != 0 { println!(\"{} {:08x}\", %s, %s.to_bits()); }" % (ref, path, ref))
            elif t[0] == "prim" and t[1] == "bool":
                out.append(pad + "if %s { println!(\"{} 1\", %s); }" % (ref, path))
            else:
                out.append(pad + "if %s != 0 { println!(\"{} {}\", %s, %s as i64); }" % (ref, path, ref))
            for d in reversed(range(len(dims))):
                pad = pad[:-4]
                out.append(pad + "}")
        out.append("}")
        out.append("")
    return out


