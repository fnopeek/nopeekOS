def parse_type(qt):
    """A C type string as clang prints it → ('prim', rust) | ('struct', name) |
    ('enum', name) | ('ptr', inner, const) | ('arr', inner, n) | ('fnptr', ret, [params])."""
    qt = qt.strip()
    m = re.match(r"^(.*)\(\*\)\((.*)\)$", qt)
    if m:
        return ("fnptr", parse_type(m.group(1)), [parse_type(p) for p in split_params(m.group(2)) if p != "void"])
    m = re.match(r"^(.*?)\s*((\[\d+\])+)$", qt)
    if m:
        dims = [int(x) for x in re.findall(r"\[(\d+)\]", m.group(2))]
        t = parse_type(m.group(1))
        for n in reversed(dims):
            t = ("arr", t, n)
        return t
    if qt.endswith("*"):
        inner = qt[:-1].strip()
        const = False
        if inner.endswith("const"):
            inner = inner[: -len("const")].strip()
        if inner.startswith("const "):
            const = True
            inner = inner[6:]
        return ("ptr", parse_type(inner), const)
    if qt.endswith(" const"):
        qt = qt[:-6]
    while qt.startswith(("const ", "volatile ")):
        qt = qt.split(" ", 1)[1]
    if qt.startswith("struct "):
        return ("struct", qt[7:].strip())
    if qt.startswith("union "):
        return ("struct", qt[6:].strip())
    if qt.startswith("enum "):
        return ("enum", qt[5:].strip())
    if qt in PRIM:
        return ("prim", PRIM[qt])
    return ("typedef", qt)


def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


class World:
    """Everything the ASTs declare: records, typedefs, enums, functions."""

    def __init__(self):
        self.records = {}   # name -> [(field, qualType)]
        self.typedefs = {}  # name -> qualType
        self.enums = {}     # name -> [(const, value)]
        self.enum_consts = {}
        self.funcs = {}     # name -> FunctionDecl node (with body)
        self.func_file = {}
        self.anon_records = {}
        self.unions = set()
        self.c_name = {}  # record -> its C spelling when that is a typedef of an anonymous struct
        self.fnptr_impl = {}  # dml_funcs field -> the function dml21_funcs binds

    def resolve(self, t):
        while t[0] == "typedef":
            if t[1] not in self.typedefs:
                raise Unsupported("typedef " + t[1])
            t = parse_type(self.typedefs[t[1]])
        if t[0] == "ptr":
            return ("ptr", self.resolve(t[1]), t[2])
        if t[0] == "arr":
            return ("arr", self.resolve(t[1]), t[2])
        return t

    def ctype(self, node_type):
        qt = node_type.get("desugaredQualType", node_type["qualType"])
        return self.resolve(parse_type(qt))

    def add(self, tu, path):
        cur = None
        for n in tu["inner"]:
            f = n.get("loc", {}).get("file")
            if f:
                cur = f
            self.add_decl(n, cur, path)

    def add_decl(self, n, cur, path):
        k = n.get("kind")
        if k == "RecordDecl" and n.get("completeDefinition"):
            name = n.get("name")
            fields = []
            for c in n.get("inner", []):
                if c.get("kind") == "FieldDecl":
                    fields.append((c.get("name") or "__anon%d" % len(fields), c["type"].get("desugaredQualType", c["type"]["qualType"]),
                                   c.get("isBitfield", False)))
                elif c.get("kind") in ("RecordDecl", "EnumDecl"):
                    self.add_decl(c, cur, path)
            if n.get("tagUsed") == "union":
                self.unions.add(name or n["id"])
            if name:
                self.records.setdefault(name, fields)
            else:
                self.anon_records[n["id"]] = fields
        elif k == "TypedefDecl":
            self.typedefs.setdefault(n["name"], n["type"].get("desugaredQualType", n["type"]["qualType"]))
            for c in n.get("inner", []):
                if c.get("kind") == "RecordType" and c.get("decl", {}).get("id") in self.anon_records:
                    tag = parse_type(n["type"]["qualType"])
                    if tag[0] == "struct":
                        self.records.setdefault(tag[1], self.anon_records[c["decl"]["id"]])
                        self.c_name.setdefault(tag[1], n["name"])
                self.add_decl(c, cur, path)
        elif k == "EnumDecl":
            name = n.get("name") or ""
            val = -1
            consts = []
            for c in n.get("inner", []):
                if c.get("kind") != "EnumConstantDecl":
                    continue
                v = None
                for e in c.get("inner", []):
                    v = const_eval(e, self)
                val = v if v is not None else val + 1
                consts.append((c["name"], val))
                self.enum_consts.setdefault(c["name"], val)
            if name and cur and "/dc/dml/" in cur:
                self.enums.setdefault(name, consts)
        elif k == "VarDecl" and n.get("name") == FUNCS_TABLE and n.get("inner"):
            fields = [f for f, _, _ in self.records.get("dml_funcs", [])]
            for fname, e in zip(fields, n["inner"][0].get("inner", [])):
                e = strip(e)
                if e.get("kind") == "DeclRefExpr":
                    self.fnptr_impl[fname] = e["referencedDecl"]["name"]
        elif k == "FunctionDecl":
            if any(c.get("kind") == "CompoundStmt" for c in n.get("inner", [])):
                if cur and (cur.endswith(path) or cur.endswith(INLINE_HDR)):
                    key = n["name"]
                    if key not in self.funcs:
                        self.funcs[key] = n
                        self.func_file[key] = INLINE_HDR if cur.endswith(INLINE_HDR) else path


def const_eval(e, w):
    k = e.get("kind")
    if k == "ConstantExpr" and "value" in e:
        return int(e["value"])
    if k == "IntegerLiteral":
        return int(e["value"])
    if k in ("ImplicitCastExpr", "ParenExpr", "ConstantExpr", "CStyleCastExpr"):
        return const_eval(e["inner"][0], w)
    if k == "UnaryOperator" and e["opcode"] == "-":
        v = const_eval(e["inner"][0], w)
        return None if v is None else -v
    if k == "DeclRefExpr" and e.get("referencedDecl", {}).get("kind") == "EnumConstantDecl":
        return w.enum_consts.get(e["referencedDecl"]["name"])
    if k == "BinaryOperator":
        a, b = (const_eval(x, w) for x in e["inner"])
        if a is None or b is None:
            return None
        return {"+": a + b, "-": a - b, "*": a * b, "<<": a << b, "|": a | b}.get(e["opcode"])
    return None


# ---------------------------------------------------------------- Rust types

def rty(w, t):
    t = w.resolve(t)
    if t[0] == "prim":
        return t[1]
    if t[0] == "enum":
        return "u32"
    if t[0] == "struct":
        return t[1]
    if t[0] == "arr":
        return "[%s; %d]" % (rty(w, t[1]), t[2])
    if t[0] == "ptr":
        inner = w.resolve(t[1])
        if inner[0] == "struct" and inner[1] == "dal_logger":
            return "()"
        return ("&" if t[2] else "&mut ") + rty(w, inner)
    if t[0] == "fnptr":
        return "Option<fn(%s)%s>" % (", ".join(param_rty_plain(w, p) for p in t[2]),
                                     "" if rty(w, t[1]) == "()" else " -> " + rty(w, t[1]))
    raise Unsupported(str(t))


def param_rty_plain(w, t):
    t = w.resolve(t)
    if t[0] == "ptr":
        inner = w.resolve(t[1])
        return ("&" if t[2] else "&mut ") + rty(w, inner)
    return rty(w, t)


def zero(w, t):
    t = w.resolve(t)
    if t[0] == "prim":
        return {"f64": "0.0", "f32": "0.0", "bool": "false", "()": "()"}.get(t[1], "0")
    if t[0] == "enum":
        return "0"
    if t[0] == "struct":
        return t[1] + "::ZERO"
    if t[0] == "arr":
        return "[%s; %d]" % (zero(w, t[1]), t[2])
    if t[0] == "fnptr":
        return "None"
    if t[0] == "ptr":
        return "()"
    raise Unsupported(str(t))


def kind_of(w, t):
    """The Rust value kind of a C type, for coercions."""
    t = w.resolve(t)
    if t[0] == "prim":
        return t[1]
    if t[0] == "enum":
        return "u32"
    return "other"


