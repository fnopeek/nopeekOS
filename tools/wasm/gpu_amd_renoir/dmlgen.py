# ---------------------------------------------------------------- functions

class Fn:
    def __init__(self, w, node):
        self.w = w
        self.node = node
        self.name = node["name"]
        self.params = [c for c in node.get("inner", []) if c.get("kind") == "ParmVarDecl"]
        self.body = [c for c in node.get("inner", []) if c.get("kind") == "CompoundStmt"][0]
        qt = node["type"]["qualType"]
        self.ret = w.resolve(parse_type(qt.split("(")[0]))
        self.pkind = {}  # param name -> 'slice' | 'ref' | 'struct' | 'value'
        for p in self.params:
            t = w.ctype(p["type"])
            if t[0] == "ptr":
                inner = w.resolve(t[1])
                if inner[0] == "struct" and not subscripted(self.body, p["id"]):
                    self.pkind[p["name"]] = "struct"
                else:
                    self.pkind[p["name"]] = "slice" if subscripted(self.body, p["id"]) else "ref"
            else:
                self.pkind[p["name"]] = "value"
        self.pmut = {p["name"]: False for p in self.params}
        self.ptr_locals = {}
        collect_ptr_locals(self.body, w, self.ptr_locals)

    def fn_type(self):
        return "fn(%s)%s" % (", ".join(t for _, t in self.param_types()),
                             "" if rty(self.w, self.ret) == "()" else " -> " + rty(self.w, self.ret))

    def param_types(self):
        out = []
        for p in self.params:
            t = self.w.ctype(p["type"])
            k = self.pkind[p["name"]]
            if k == "value":
                out.append((p["name"], rty(self.w, t)))
                continue
            inner = self.w.resolve(t[1])
            if inner[0] == "struct" and inner[1] == "dal_logger":
                out.append(("_" + p["name"], "()"))
                continue
            m = "&mut " if self.pmut[p["name"]] else "&"
            base = rty(self.w, inner)
            out.append((p["name"], m + ("[%s]" % base if k == "slice" else base)))
        return out

    def sig(self, fns):
        out = []
        for p in self.params:
            t = self.w.ctype(p["type"])
            k = self.pkind[p["name"]]
            if k == "value":
                out.append("%s: %s" % (rname(p["name"]), rty(self.w, t)))
            else:
                inner = self.w.resolve(t[1])
                if inner[0] == "struct" and inner[1] == "dal_logger":
                    out.append("_%s: ()" % p["name"])
                    continue
                m = "&mut " if self.pmut[p["name"]] else "&"
                base = rty(self.w, inner)
                out.append("%s: %s%s" % (rname(p["name"]), m, "[%s]" % base if k == "slice" else base))
        r = rty(self.w, self.ret)
        return "pub fn %s(%s)%s" % (rname(self.name), ", ".join(out), "" if r == "()" else " -> " + r)


def collect_ptr_locals(n, w, out):
    if isinstance(n, dict):
        if n.get("kind") == "VarDecl" and n.get("inner") and w.ctype(n["type"])[0] == "ptr":
            out[n["id"]] = n["inner"][0]
        for c in n.get("inner", []):
            collect_ptr_locals(c, w, out)


def root_param(n, f, depth=0):
    """The pointer parameter a place or pointer expression is reached through."""
    while True:
        k = n.get("kind")
        if k in ("ImplicitCastExpr", "CStyleCastExpr", "ParenExpr"):
            n = n["inner"][0]
        elif k in ("MemberExpr", "ArraySubscriptExpr"):
            n = n["inner"][0]
        elif k == "UnaryOperator" and n["opcode"] in ("*", "&"):
            n = n["inner"][0]
        elif k == "BinaryOperator" and n["opcode"] in ("+", "-"):
            n = n["inner"][0]
        elif k == "DeclRefExpr":
            d = n["referencedDecl"]
            for p in f.params:
                if p["id"] == d["id"]:
                    return p["name"] if f.pkind[p["name"]] != "value" else None
            if d["id"] in f.ptr_locals and depth < 8:
                return root_param(f.ptr_locals[d["id"]], f, depth + 1)
            return None
        else:
            return None


def place_path(n, f, depth=0):
    """(parameter, member path) of a place or pointer expression reached
    through a pointer parameter; subscripts drop out (the whole array)."""
    path = []
    while True:
        k = n.get("kind")
        if k in ("ImplicitCastExpr", "CStyleCastExpr", "ParenExpr"):
            n = n["inner"][0]
        elif k == "MemberExpr":
            path.append(n["name"])
            n = n["inner"][0]
        elif k == "ArraySubscriptExpr":
            n = n["inner"][0]
        elif k == "UnaryOperator" and n["opcode"] in ("*", "&"):
            n = n["inner"][0]
        elif k == "BinaryOperator" and n["opcode"] in ("+", "-"):
            n = n["inner"][0]
        elif k == "DeclRefExpr":
            d = n["referencedDecl"]
            for p in f.params:
                if p["id"] == d["id"]:
                    if f.pkind[p["name"]] == "value":
                        return None
                    return p["name"], tuple(reversed(path))
            if d["id"] in f.ptr_locals and depth < 8:
                r = place_path(f.ptr_locals[d["id"]], f, depth + 1)
                if r:
                    return r[0], r[1] + tuple(reversed(path))
            return None
        else:
            return None


def overlap(p, q):
    n = min(len(p), len(q))
    return p[:n] == q[:n]


CHAIN = ("MemberExpr", "ArraySubscriptExpr", "ImplicitCastExpr", "ParenExpr", "CStyleCastExpr")


def analyze_access(fns):
    """Per struct parameter, the member paths a function reads or writes
    (acc) and writes (wr), through its callees too; to a fixpoint."""
    for f in fns.values():
        f.acc = {p["name"]: set() for p in f.params}
        f.wr = {p["name"]: set() for p in f.params}
    changed = True
    while changed:
        changed = False
        for f in fns.values():
            acc, wr = set(), set()
            access_walk(f.body, f, fns, acc, wr, False)
            for (r, pth) in acc:
                if pth not in f.acc[r]:
                    f.acc[r].add(pth)
                    changed = True
            for (r, pth) in wr:
                if pth not in f.wr[r]:
                    f.wr[r].add(pth)
                    changed = True


def access_walk(n, f, fns, acc, wr, in_chain):
    if not isinstance(n, dict):
        return
    k = n.get("kind")
    if k in CHAIN or (k == "UnaryOperator" and n.get("opcode") in ("*", "&")) or k == "DeclRefExpr":
        if not in_chain:
            pp = place_path(n, f)
            if pp:
                acc.add(pp)
        if k == "ArraySubscriptExpr":
            access_walk(n["inner"][0], f, fns, acc, wr, True)
            access_walk(n["inner"][1], f, fns, acc, wr, False)
        else:
            for c in n.get("inner", []):
                access_walk(c, f, fns, acc, wr, k != "DeclRefExpr")
        return
    if k in ("BinaryOperator", "CompoundAssignOperator") and n.get("opcode", "").endswith("=") and \
            n["opcode"] not in ("==", "!=", "<=", ">="):
        pp = place_path(n["inner"][0], f)
        if pp:
            wr.add(pp)
    if k == "UnaryOperator" and n["opcode"] in ("++", "--"):
        pp = place_path(n["inner"][0], f)
        if pp:
            wr.add(pp)
    if k == "CallExpr":
        cs = strip(n["inner"][0])
        args = n["inner"][1:]
        if cs.get("kind") == "DeclRefExpr":
            name = cs["referencedDecl"]["name"]
            g = fns.get(name)
            if name in ("memset", "memcpy"):
                pp = place_path(args[0], f)
                if pp:
                    wr.add(pp)
            if g:
                for a, p in zip(args, g.params):
                    pk = g.pkind[p["name"]]
                    pp = place_path(a, f)
                    if pk == "struct" and pp:
                        for q in g.acc[p["name"]]:
                            acc.add((pp[0], pp[1] + q))
                        for q in g.wr[p["name"]]:
                            wr.add((pp[0], pp[1] + q))
                        continue
                    if pk != "value" and pp:
                        acc.add(pp)
                        if g.pmut[p["name"]]:
                            wr.add(pp)
                    access_walk(a, f, fns, acc, wr, False)
                return
        else:
            for a in args:
                pp = place_path(a, f)
                if pp:
                    acc.add(pp)
                    wr.add(pp)
    for c in n.get("inner", []):
        access_walk(c, f, fns, acc, wr, False)


def propagate_slices(fns):
    """A pointer parameter handed on to a callee's slice parameter is a
    slice too; to a fixpoint."""
    changed = True
    while changed:
        changed = False
        for f in fns.values():
            ids = {p["id"]: p["name"] for p in f.params}

            def walk(n):
                nonlocal changed
                if not isinstance(n, dict):
                    return
                if n.get("kind") == "CallExpr":
                    cs = strip(n["inner"][0])
                    if cs.get("kind") == "DeclRefExpr" and cs["referencedDecl"]["name"] in fns:
                        g = fns[cs["referencedDecl"]["name"]]
                        for a, p in zip(n["inner"][1:], g.params):
                            sa = strip(a)
                            if g.pkind[p["name"]] == "slice" and sa.get("kind") == "DeclRefExpr":
                                nm = ids.get(sa["referencedDecl"]["id"])
                                if nm and f.pkind[nm] in ("struct", "ref"):
                                    f.pkind[nm] = "slice"
                                    changed = True
                for c in n.get("inner", []):
                    walk(c)

            walk(f.body)


def analyze_writes(fns):
    """Which pointer parameters a function writes through, directly or by
    handing them to a callee that does; to a fixpoint."""
    changed = True
    while changed:
        changed = False
        for f in fns.values():
            for name in writes_of(f.body, f, fns):
                if not f.pmut.get(name, True):
                    f.pmut[name] = True
                    changed = True


def writes_of(n, f, fns):
    out = set()

    def mark(x):
        r = root_param(x, f)
        if r:
            out.add(r)

    def walk(n):
        if not isinstance(n, dict):
            return
        k = n.get("kind")
        if k in ("BinaryOperator", "CompoundAssignOperator") and n.get("opcode", "").endswith("=") and \
                n["opcode"] not in ("==", "!=", "<=", ">="):
            mark(n["inner"][0])
        elif k == "UnaryOperator" and n["opcode"] in ("++", "--"):
            mark(n["inner"][0])
        elif k == "CallExpr":
            cs = strip(n["inner"][0])
            args = n["inner"][1:]
            if cs.get("kind") == "DeclRefExpr":
                name = cs["referencedDecl"]["name"]
                if name in ("memset", "memcpy"):
                    mark(args[0])
                elif name in fns:
                    g = fns[name]
                    for a, p in zip(args, g.params):
                        if g.pkind[p["name"]] != "value" and g.pmut[p["name"]]:
                            mark(a)
            else:
                for a in args:
                    mark(a)
        for c in n.get("inner", []):
            walk(c)

    walk(n)
    return out


def subscripted(n, pid):
    """Whether the parameter with clang id `pid` is used as an array: the
    base of a subscript, or a memcmp/memcpy operand of `sizeof(T) * n`."""
    if n.get("kind") == "ArraySubscriptExpr":
        b = strip(n["inner"][0])
        if b.get("kind") == "DeclRefExpr" and b.get("referencedDecl", {}).get("id") == pid:
            return True
    if n.get("kind") == "CallExpr":
        cs = strip(n["inner"][0])
        if cs.get("kind") == "DeclRefExpr" and cs["referencedDecl"]["name"] in ("memcmp", "memcpy"):
            size = n["inner"][3]
            while size.get("kind") in ("ImplicitCastExpr", "ParenExpr"):
                size = size["inner"][0]
            if size.get("kind") == "BinaryOperator" and size["opcode"] == "*":
                for a in n["inner"][1:3]:
                    b = a
                    while b.get("kind") in ("ImplicitCastExpr", "ParenExpr"):
                        b = b["inner"][0]
                    if b.get("kind") == "DeclRefExpr" and b.get("referencedDecl", {}).get("id") == pid:
                        return True
    return any(subscripted(c, pid) for c in n.get("inner", []) if isinstance(c, dict))


def strip(n):
    while n.get("kind") in ("ImplicitCastExpr", "ParenExpr") and n.get("castKind", "NoOp") in (
            "LValueToRValue", "ArrayToPointerDecay", "NoOp", "FunctionToPointerDecay", None) or (
            n.get("kind") == "ParenExpr"):
        n = n["inner"][0]
    return n


class Gen:
    def __init__(self, w, fn, fns):
        self.w = w
        self.fn = fn
        self.fns = fns
        self.alias = {}   # var id -> lvalue string
        self.vars = {}    # var id -> ('param'|'local', kind, ctype)
        for p in fn.params:
            self.vars[p["id"]] = ("param", fn.pkind[p["name"]], w.ctype(p["type"]), p["name"])
        self.loop_inc = []
        self.tmp = 0

    # ---- expressions: (code, kind)
    def ty(self, n):
        return self.w.ctype(n["type"])

    def ex(self, n):
        k = n["kind"]
        f = getattr(self, "e_" + k, None)
        if not f:
            raise Unsupported("expr " + k + " in " + self.fn.name)
        return f(n)

    def e_ParenExpr(self, n):
        c, k = self.ex(n["inner"][0])
        return "(%s)" % c, k

    def e_IntegerLiteral(self, n):
        k = kind_of(self.w, self.ty(n))
        return "%s_%s" % (n["value"], k), k

    def e_FloatingLiteral(self, n):
        k = kind_of(self.w, self.ty(n))
        v = n["value"]
        if not re.search(r"[.eEn]", v):
            v += ".0"
        return "%s_%s" % (v, k), k

    def e_CharacterLiteral(self, n):
        return "%s_i8" % n["value"], "i8"

    def e_ConstantExpr(self, n):
        return self.ex(n["inner"][0])

    def e_DeclRefExpr(self, n):
        d = n["referencedDecl"]
        if d["kind"] == "EnumConstantDecl":
            k = kind_of(self.w, self.ty(n))
            return ("%s" % d["name"]) if k == "u32" else "(%s as %s)" % (d["name"], k), k
        if d["kind"] == "FunctionDecl":
            return rname(d["name"]), "fn"
        return self.lv(n), self.kind_of_lv(n)

    def kind_of_lv(self, n):
        return kind_of(self.w, self.ty(n))

    def e_MemberExpr(self, n):
        return self.lv(n), self.kind_of_lv(n)

    def e_ArraySubscriptExpr(self, n):
        return self.lv(n), self.kind_of_lv(n)

    def e_ImplicitCastExpr(self, n):
        return self.cast(n)

    def e_CStyleCastExpr(self, n):
        c, k = self.cast(n)
        return "(%s)" % c, k

    def cast(self, n):
        ck = n["castKind"]
        inner = n["inner"][0]
        to = kind_of(self.w, self.ty(n))
        if ck in ("LValueToRValue", "NoOp", "FunctionToPointerDecay", "ArrayToPointerDecay"):
            return self.ex(inner)
        c, frm = self.ex(inner)
        if ck == "IntegralCast":
            if frm == "bool" and to != "bool":
                return "((%s) as %s)" % (c, to), to
            if frm == to:
                return c, to
            return "((%s) as %s)" % (c, to), to
        if ck == "IntegralToFloating":
            if frm == "bool":
                c = "((%s) as i32)" % c
            return "((%s) as %s)" % (c, to), to
        if ck == "FloatingCast":
            return "((%s) as %s)" % (c, to), to
        if ck == "FloatingToIntegral":
            src = c if frm == "f64" else "((%s) as f64)" % c
            if to in ("i32", "i8", "i16", "u8", "u16"):
                return "(dml_math::f2i32(%s) as %s)" % (src, to) if to != "i32" else "dml_math::f2i32(%s)" % src, to
            if to == "u32":
                return "dml_math::f2u32(%s)" % src, to
            if to in ("i64", "u64"):
                return "(dml_math::f2i64(%s) as %s)" % (src, to), to
            raise Unsupported("f2i " + to)
        if ck == "IntegralToBoolean":
            if frm == "bool":
                return c, "bool"
            return "((%s) != 0)" % c, "bool"
        if ck == "FloatingToBoolean":
            return "((%s) != 0.0)" % c, "bool"
        if ck == "BooleanToSignedIntegral":
            return "((%s) as %s)" % (c, to), to
        raise Unsupported("cast " + ck + " in " + self.fn.name)

    def as_kind(self, code, frm, to):
        if frm == to or to == "other" or frm in ("other", "fn"):
            return code
        if frm == "bool" and to in INTS:
            return "((%s) as %s)" % (code, to)
        if frm == "bool" and to in FLOATS:
            return "(((%s) as i32) as %s)" % (code, to)
        if to == "bool":
            return "((%s) != 0)" % code if frm in INTS else "((%s) != 0.0)" % code
        return "((%s) as %s)" % (code, to)

    def cond(self, n):
        c, k = self.ex(n)
        if k == "bool":
            return c
        if k in INTS:
            return "(%s) != 0" % c
        if k in FLOATS:
            return "(%s) != 0.0" % c
        raise Unsupported("cond " + k)

    def e_BinaryOperator(self, n):
        op = n["opcode"]
        a, b = n["inner"]
        if op == "=":
            return self.assign(n), "stmt"
        if op in ("&&", "||"):
            return "(%s %s %s)" % (self.cond(a), op, self.cond(b)), "bool"
        if op == ",":
            raise Unsupported("comma")
        ca, ka = self.ex(a)
        cb, kb = self.ex(b)
        if op in ("==", "!=", "<", ">", "<=", ">="):
            if ka == "bool" and kb != "bool":
                ca = self.as_kind(ca, "bool", kb)
            if kb == "bool" and ka != "bool":
                cb = self.as_kind(cb, "bool", ka)
            return "(%s %s %s)" % (ca, op, cb), "bool"
        k = kind_of(self.w, self.ty(n))
        ca = self.as_kind(ca, ka, k) if op not in ("<<", ">>") else ca
        cb = self.as_kind(cb, kb, k) if op not in ("<<", ">>") else cb
        if op in ("<<", ">>"):
            return "(%s %s %s)" % (self.as_kind(ca, ka, k), op, cb), k
        if op == "%" and k in FLOATS:
            raise Unsupported("float %")
        if op in ("+", "-", "*") and k in INTS:
            fnm = {"+": "wrapping_add", "-": "wrapping_sub", "*": "wrapping_mul"}[op]
            return "(%s).%s(%s)" % (ca, fnm, cb), k
        return "(%s %s %s)" % (ca, op, cb), k

    def e_ConditionalOperator(self, n):
        c, a, b = n["inner"]
        k = kind_of(self.w, self.ty(n))
        ca, ka = self.ex(a)
        cb, kb = self.ex(b)
        return "(if %s { %s } else { %s })" % (self.cond(c), self.as_kind(ca, ka, k), self.as_kind(cb, kb, k)), k

    def e_UnaryOperator(self, n):
        op = n["opcode"]
        x = n["inner"][0]
        if op == "!":
            return "(!(%s))" % self.cond(x), "bool"
        if op == "-":
            c, k = self.ex(x)
            if k in INTS:
                return "(%s).wrapping_neg()" % c, k
            return "(-%s)" % c, k
        if op == "+":
            return self.ex(x)
        if op == "~":
            c, k = self.ex(x)
            return "(!%s)" % c, k
        if op == "*":
            return self.lv(n), self.kind_of_lv(n)
        if op in ("++", "--"):
            raise Unsupported("++ in expression")
        if op == "&":
            raise Unsupported("& outside a call argument")
        raise Unsupported("unary " + op)

    def e_CallExpr(self, n):
        callee = n["inner"][0]
        args = n["inner"][1:]
        cs = strip(callee)
        if cs.get("kind") == "DeclRefExpr":
            name = cs["referencedDecl"]["name"]
            if name in ("printf", "pr_debug", "dm_output_to_console", "_printk", "dml_print", "__builtin_expect"):
                return "()", "()"
            if name in HAND:
                node = self.w.funcs[name]
                ps = [c for c in node.get("inner", []) if c.get("kind") == "ParmVarDecl"]
                cargs = []
                for a, p in zip(args, ps):
                    c, ka = self.ex(a)
                    cargs.append(self.as_kind(c, ka, kind_of(self.w, self.w.ctype(p["type"]))))
                ret = self.w.resolve(parse_type(node["type"]["qualType"].split("(")[0]))
                return "dml_math::%s(%s)" % (name, ", ".join(cargs)), kind_of(self.w, ret)
            if name in ("memcmp", "memcpy", "memset"):
                return self.mem(name, args)
            f = self.fns.get(name)
            if not f:
                raise Unsupported("call to " + name)
            argc = [self.arg(a, f, i) for i, a in enumerate(args)]
            pre, post = self.resolve_aliasing(f, args, argc)
            if any(f.pkind[p["name"]] != "value" for p in f.params):
                lets = []
                for i, p in enumerate(f.params):
                    if f.pkind[p["name"]] == "value" and not re.fullmatch(r"[\w.]+_\w+", argc[i]):
                        self.tmp += 1
                        lets.append("let __a%d = %s;" % (self.tmp, argc[i]))
                        argc[i] = "__a%d" % self.tmp
                lets += pre
                if post:
                    self.tmp += 1
                    return "{ %s let __r%d = %s(%s); %s __r%d }" % (" ".join(lets), self.tmp, self.path(name),
                                                                    ", ".join(argc), " ".join(post), self.tmp), \
                        kind_of(self.w, f.ret)
                if lets:
                    return "{ %s %s(%s) }" % (" ".join(lets), self.path(name), ", ".join(argc)), kind_of(self.w, f.ret)
            code = "%s(%s)" % (self.path(name), ", ".join(argc))
            return code, kind_of(self.w, f.ret)
        if cs.get("kind") == "MemberExpr" and cs["name"] in self.w.fnptr_impl:
            # a call through the DML vtable: argued as the function it holds
            f = self.fns[self.w.fnptr_impl[cs["name"]]]
            argc = [self.arg(a, f, i) for i, a in enumerate(args)]
            pre, post = self.resolve_aliasing(f, args, argc)
            self.tmp += 1
            fp = "__fp%d" % self.tmp
            lets = ["let %s = %s.unwrap();" % (fp, self.lv(cs))]
            for i, p in enumerate(f.params):
                if f.pkind[p["name"]] == "value" and not re.fullmatch(r"[\w.]+_\w+", argc[i]):
                    self.tmp += 1
                    lets.append("let __a%d = %s;" % (self.tmp, argc[i]))
                    argc[i] = "__a%d" % self.tmp
            lets += pre
            self.tmp += 1
            return "{ %s let __r%d = %s(%s); %s __r%d }" % (" ".join(lets), self.tmp, fp, ", ".join(argc),
                                                            " ".join(post), self.tmp), kind_of(self.w, f.ret)
        raise Unsupported("indirect call")

    def resolve_aliasing(self, f, args, argc):
        """Pointer arguments that reach into the same struct as another
        argument: Rust cannot borrow both, C does not care. Pass a copy
        (read-only parameter) or copy in and out (written parameter), but
        only where the callee is shown not to touch that member through the
        other argument; otherwise stop."""
        infos = []
        for i, (a, p) in enumerate(zip(args, f.params)):
            pk = f.pkind[p["name"]]
            if pk == "value":
                continue
            pp = place_path(a, self.fn)
            if not pp:
                continue
            infos.append((i, p["name"], pk, f.pmut[p["name"]], pp))
        pre, post = [], []
        done = set()
        for i, pn, pk, mut, (root, P) in infos:
            for j, qn, qk, qmut, (root2, SP) in infos:
                if i == j or root != root2 or i in done:
                    continue
                if not (mut or qmut):
                    continue
                if qk == "struct" and pk != "struct":
                    if not (P[:len(SP)] == SP):
                        if SP[:len(P)] == P:
                            raise Unsupported("argument %d contains struct argument %d" % (i, j))
                        continue
                    R = P[len(SP):]
                    bad = f.acc[qn] if mut else f.wr[qn]
                    if any(overlap(R, q) for q in bad):
                        raise Unsupported("argument %d aliases what %s reaches through %s" % (i, f.name, qn))
                elif pk == "struct" or qk == "struct":
                    continue
                elif not overlap(P, SP) or not mut:
                    continue
                self.copy_arg(i, f, args, argc, mut, pre, post)
                done.add(i)
        return pre, post

    def copy_arg(self, i, f, args, argc, mut, pre, post):
        p = f.params[i]
        tpl, base = self.ptr_arg_t(args[i], f.pkind[p["name"]], not mut)
        if base is None:
            raise Unsupported("aliased pointer parameter passed on")
        self.tmp += 1
        t = "__c%d" % self.tmp
        if mut:
            pre.append("let mut %s = %s;" % (t, base))
            post.append("%s = %s;" % (base, t))
        else:
            pre.append("let %s = %s;" % (t, base))
        argc[i] = tpl.replace("@@", t)

    def mem_count(self, n):
        """The element count of a `sizeof(T)` or `sizeof(T) * n` size."""
        s = strip(n)
        while s.get("kind") == "ImplicitCastExpr":
            s = strip(s["inner"][0])
        if s.get("kind") == "UnaryExprOrTypeTraitExpr":
            return None
        if s.get("kind") == "BinaryOperator" and s["opcode"] == "*":
            a, b = s["inner"]
            if strip(a).get("kind") == "UnaryExprOrTypeTraitExpr":
                c, k = self.ex(b)
            else:
                c, k = self.ex(a)
            return "(%s) as usize" % c
        raise Unsupported("mem size")

    def mem_place(self, n, count):
        s = strip(n)
        while s.get("kind") == "ImplicitCastExpr":
            s = strip(s["inner"][0])
        if s.get("kind") == "UnaryOperator" and s["opcode"] == "&":
            return self.lv(s["inner"][0])
        if s.get("kind") == "DeclRefExpr":
            v = self.vars.get(s["referencedDecl"]["id"])
            if v and v[1] == "struct" and count is None:
                return "(*%s)" % rname(v[3])
        return self.lv(s)

    def mem(self, name, args):
        if name == "memset":
            cnt = self.mem_count(args[2])
            v, _ = self.ex(args[1])
            if cnt is not None or not v.startswith("0"):
                raise Unsupported("memset form")
            place = self.mem_place(args[0], None)
            return "%s = Default::default()" % place, "stmt"
        cnt = self.mem_count(args[2])
        a = self.mem_place(args[0], cnt)
        b = self.mem_place(args[1], cnt)
        if name == "memcpy":
            if cnt is None:
                return "%s = %s" % (a, b), "stmt"
            return "%s[..%s].copy_from_slice(&%s[..%s])" % (a, cnt, b, cnt), "stmt"
        if cnt is None:
            return "(if %s.bits_eq(&%s) { 0_i32 } else { 1_i32 })" % (a, b), "i32"
        return "(if bits_eq_slice(&%s[..%s], &%s[..%s]) { 0_i32 } else { 1_i32 })" % (a, cnt, b, cnt), "i32"

    def path(self, name):
        f = self.w.func_file.get(name)
        mod = MODULE_OF.get(f)
        if name in HAND:
            return "dml_math::" + name
        if mod and mod != CURRENT_MOD[0]:
            return "%s::%s" % (mod, rname(name))
        return rname(name)

    def arg(self, a, f, i):
        p = f.params[i]
        k = f.pkind[p["name"]]
        if k == "value":
            c, ka = self.ex(a)
            return self.as_kind(c, ka, kind_of(self.w, self.w.ctype(p["type"])))
        t = self.w.ctype(p["type"])
        inner = self.w.resolve(t[1])
        if inner[0] == "struct" and inner[1] == "dal_logger":
            return "()"
        return self.ptr_arg(a, k, not f.pmut[p["name"]])

    def arg_by_type(self, a, pt):
        pt = self.w.resolve(pt)
        if pt[0] != "ptr":
            c, ka = self.ex(a)
            return self.as_kind(c, ka, kind_of(self.w, pt))
        inner = self.w.resolve(pt[1])
        return self.ptr_arg(a, "struct" if inner[0] == "struct" else "ref", pt[2])

    def ptr_arg(self, a, k, const):
        tpl, base = self.ptr_arg_t(a, k, const)
        return tpl.replace("@@", base) if base is not None else tpl

    def ptr_arg_t(self, a, k, const):
        """A pointer argument as a template over its base place: (code with
        @@ for the place, place), or (code, None) when it passes a pointer
        parameter on."""
        m = "&" if const else "&mut "
        s = strip(a)
        if s.get("kind") == "ImplicitCastExpr" and s.get("castKind") == "BitCast":
            to = self.w.ctype(s["type"])
            frm = self.w.ctype(s["inner"][0]["type"])
            if to[0] == "ptr" and frm[0] == "ptr":
                tpl, base = self.ptr_arg_t(s["inner"][0], k, const)
                fn = ("reint_slice" if k == "slice" else "reint") + ("" if const else "_mut")
                return "dml_math::%s::<%s, %s>(%s)" % (fn, kind_of(self.w, frm[1]), kind_of(self.w, to[1]), tpl), base
        if s.get("kind") == "UnaryOperator" and s["opcode"] == "&":
            if k == "slice":
                if s["inner"][0]["kind"] == "ArraySubscriptExpr":
                    base, idx = self.sub_parts(s["inner"][0])
                    return "%s@@[%s..]" % (m, idx), base
                return ("core::slice::from_mut(%s@@)" if not const else "core::slice::from_ref(%s@@)") % m, \
                    self.lv(s["inner"][0])
            return m + "@@", self.lv(s["inner"][0])
        if s.get("kind") == "BinaryOperator" and s["opcode"] == "+":
            base = self.lv(strip(s["inner"][0]))
            c, kk = self.ex(s["inner"][1])
            return "%s@@[(%s) as usize..]" % (m, c), base
        if s.get("kind") == "DeclRefExpr":
            vid = s["referencedDecl"]["id"]
            if vid in self.alias:
                if k == "slice" and self.w.ctype(s["type"])[0] == "ptr" and \
                        self.w.ctype(self.fn.ptr_locals[vid]["type"])[0] == "arr":
                    return m + "@@[..]", self.alias[vid]
                return m + "@@", self.alias[vid]
            v = self.vars.get(vid)
            t = self.w.ctype(s["type"])
            if v and v[0] == "param" and v[1] in ("ref", "slice", "struct"):
                n = rname(v[3])
                if k == "slice" and v[1] == "ref":
                    return ("core::slice::from_mut(%s)" if not const else "core::slice::from_ref(%s)") % n, None
                if k == "ref" and v[1] == "slice":
                    return "%s%s[0]" % (m, n), None
                return ("%s*%s" % (m, n)) if k != "slice" else "%s%s[..]" % (m, n), None
            if t[0] == "arr":
                return (m + "@@[..]") if k == "slice" else m + "@@[0]", self.lv(s)
        if s.get("kind") in ("MemberExpr", "ArraySubscriptExpr") and self.w.ctype(s["type"])[0] == "arr":
            return (m + "@@[..]") if k == "slice" else m + "@@[0]", self.lv(s)
        if s.get("kind") == "MemberExpr" and self.w.ctype(s["type"])[0] == "ptr":
            raise Unsupported("pointer member as argument")
        raise Unsupported("pointer argument %s/%s line %s" % (s.get("kind", "?"), s.get("castKind"),
                          a.get("range", {}).get("begin", {}).get("line", a.get("range", {}).get("begin", {}).get(
                              "expansionLoc", {}).get("line"))))

    def sub_parts(self, n):
        base = strip(n["inner"][0])
        c, k = self.ex(n["inner"][1])
        return self.lv(base), "(%s) as usize" % c

    # ---- places
    def lv(self, n):
        k = n["kind"]
        if k in ("ParenExpr",):
            return self.lv(n["inner"][0])
        if k == "ImplicitCastExpr" and n["castKind"] in ("LValueToRValue", "ArrayToPointerDecay", "NoOp"):
            return self.lv(n["inner"][0])
        if k == "DeclRefExpr":
            d = n["referencedDecl"]
            if d["id"] in self.alias:
                return self.alias[d["id"]]
            v = self.vars.get(d["id"])
            if v and v[0] == "param" and v[1] == "ref":
                return "(*%s)" % rname(d["name"])
            return rname(d["name"])
        if k == "MemberExpr":
            base = n["inner"][0]
            return "%s.%s" % (self.lv(base), rname(n["name"]))
        if k == "ArraySubscriptExpr":
            b, i = self.sub_parts(n)
            return "%s[%s]" % (b, i)
        if k == "UnaryOperator" and n["opcode"] == "*":
            x = strip(n["inner"][0])
            if x.get("kind") == "DeclRefExpr":
                vid = x["referencedDecl"]["id"]
                if vid in self.alias:
                    return self.alias[vid]
                v = self.vars.get(vid)
                if v and v[1] == "slice":
                    return "%s[0]" % rname(v[3])
                if v and v[1] in ("ref", "struct"):
                    return "(*%s)" % rname(v[3])
            raise Unsupported("deref of " + x.get("kind", "?"))
        raise Unsupported("place " + k + " in " + self.fn.name)

    # ---- statements
    def assign(self, n):
        a, b = n["inner"]
        place = self.lv(a)
        c, kb = self.ex(b)
        return "%s = %s" % (place, self.as_kind(c, kb, kind_of(self.w, self.ty(a))))

    def stmt(self, n, out, ind):
        k = n.get("kind")
        pad = "    " * ind
        if k is None or k == "NullStmt":
            return
        if k == "CompoundStmt":
            out.append(pad + "{")
            for c in n.get("inner", []):
                self.stmt(c, out, ind + 1)
            out.append(pad + "}")
            return
        if k == "DeclStmt":
            for d in n["inner"]:
                self.decl(d, out, pad)
            return
        if k == "ReturnStmt":
            if n.get("inner"):
                c, kk = self.ex(n["inner"][0])
                out.append(pad + "return %s;" % self.as_kind(c, kk, kind_of(self.w, self.fn.ret)))
            else:
                out.append(pad + "return;")
            return
        if k == "IfStmt":
            inner = n["inner"]
            out.append(pad + "if %s {" % self.cond(inner[0]))
            self.body(inner[1], out, ind + 1)
            if len(inner) > 2:
                out.append(pad + "} else {")
                self.body(inner[2], out, ind + 1)
            out.append(pad + "}")
            return
        if k == "ForStmt":
            init, _cv, cond, inc, body = n["inner"]
            out.append(pad + "{")
            if init:
                self.stmt(init, out, ind + 1)
            out.append(pad + "    while %s {" % (self.cond(cond) if cond else "true"))
            incs = []
            if inc:
                self.stmt(inc, incs, ind + 2)
            self.loop_inc.append(incs)
            self.body(body, out, ind + 2)
            self.loop_inc.pop()
            out.extend(incs)
            out.append(pad + "    }")
            out.append(pad + "}")
            return
        if k == "WhileStmt":
            cond, body = n["inner"]
            out.append(pad + "while %s {" % self.cond(cond))
            self.loop_inc.append([])
            self.body(body, out, ind + 1)
            self.loop_inc.pop()
            out.append(pad + "}")
            return
        if k == "DoStmt":
            body, cond = n["inner"]
            cv = const_eval(cond, self.w)
            if cv == 0 and not has_jump(body):
                self.body(body, out, ind)
                return
            out.append(pad + "loop {")
            self.loop_inc.append(None)
            self.body(body, out, ind + 1)
            self.loop_inc.pop()
            out.append(pad + "    if !(%s) { break; }" % self.cond(cond))
            out.append(pad + "}")
            return
        if k == "SwitchStmt":
            self.switch(n, out, ind)
            return
        if k == "BreakStmt":
            top = self.loop_inc[-1] if self.loop_inc else None
            if isinstance(top, tuple):
                out.append(pad + "break %s;" % top[1])
            else:
                out.append(pad + "break;")
            return
        if k == "ContinueStmt":
            inc = next(x for x in reversed(self.loop_inc) if not isinstance(x, tuple))
            if inc is None:
                raise Unsupported("continue in do-while")
            out.extend("    " + l if False else l for l in inc)
            out.append(pad + "continue;")
            return
        if k == "UnaryOperator" and n["opcode"] in ("++", "--"):
            place = self.lv(n["inner"][0])
            kk = self.kind_of_lv(n["inner"][0])
            one = "1" if kk in INTS else "1.0"
            if kk in INTS:
                out.append(pad + "%s = %s.%s(1);" % (place, place, "wrapping_add" if n["opcode"] == "++" else
                                                      "wrapping_sub"))
            else:
                out.append(pad + "%s %s= %s;" % (place, "+" if n["opcode"] == "++" else "-", one))
            return
        if k == "BinaryOperator" and n["opcode"] == "=":
            out.append(pad + self.assign(n) + ";")
            return
        if k == "CompoundAssignOperator":
            a, b = n["inner"]
            place = self.lv(a)
            c, kb = self.ex(b)
            lt = kind_of(self.w, self.ty(a))
            ct = kind_of(self.w, self.w.resolve(parse_type(n["computeResultType"]["qualType"])))
            op = n["opcode"][:-1]
            cur = self.as_kind(place, lt, ct)
            val = self.as_kind(c, kb, ct)
            if ct in INTS and op in "+-*":
                expr = "(%s).%s(%s)" % (cur, {"+": "wrapping_add", "-": "wrapping_sub", "*": "wrapping_mul"}[op], val)
            else:
                expr = "(%s %s %s)" % (cur, op, val)
            out.append(pad + "%s = %s;" % (place, self.as_kind(expr, ct, lt)))
            return
        if k == "CallExpr":
            c, kk = self.ex(n)
            if c != "()":
                out.append(pad + c + ";")
            return
        if k in ("ImplicitCastExpr", "CStyleCastExpr", "ParenExpr") and n.get("castKind", "ToVoid") in (
                "ToVoid", "NoOp"):
            self.stmt(n["inner"][0], out, ind)
            return
        raise Unsupported("stmt " + k + " in " + self.fn.name)

    def switch(self, n, out, ind):
        """C switch as a labelled block: each case group runs when its label
        matches or an earlier group fell through into it."""
        pad = "    " * ind
        cond, body = n["inner"][0], n["inner"][-1]
        self.tmp += 1
        lab = "'sw%d" % self.tmp
        sv = "__sw%d" % self.tmp
        mv = "__fall%d" % self.tmp
        c, kc = self.ex(cond)
        groups = []  # (labels, is_default, stmts)
        for st in body.get("inner", []):
            labels, dflt = [], False
            while st.get("kind") in ("CaseStmt", "DefaultStmt"):
                if st["kind"] == "CaseStmt":
                    v, kv = self.ex(st["inner"][0])
                    labels.append(self.as_kind(v, kv, kc))
                else:
                    dflt = True
                st = st["inner"][-1]
            if labels or dflt:
                groups.append((labels, dflt, [st]))
            else:
                if not groups:
                    raise Unsupported("statement before the first case")
                groups[-1][2].append(st)
        all_labels = [l for g in groups for l in g[0]]
        out.append(pad + "%s: {" % lab)
        out.append(pad + "    let %s = %s;" % (sv, c))
        out.append(pad + "    let mut %s = false;" % mv)
        dcond = "!(%s)" % " || ".join("%s == %s" % (sv, l) for l in all_labels) if all_labels else "true"
        self.loop_inc.append(("switch", lab))
        for labels, dflt, stmts in groups:
            conds = ["%s == %s" % (sv, l) for l in labels] + ([dcond] if dflt else [])
            out.append(pad + "    if %s || %s {" % (mv, " || ".join(conds)))
            out.append(pad + "        %s = true;" % mv)
            for st in stmts:
                self.stmt(st, out, ind + 2)
            out.append(pad + "    }")
        self.loop_inc.pop()
        out.append(pad + "}")

    def body(self, n, out, ind):
        if n.get("kind") == "CompoundStmt":
            for c in n.get("inner", []):
                self.stmt(c, out, ind)
        else:
            self.stmt(n, out, ind)

    def decl(self, d, out, pad):
        if d.get("kind") == "EnumDecl":
            val = -1
            for c in d.get("inner", []):
                if c.get("kind") == "EnumConstantDecl":
                    v = None
                    for e in c.get("inner", []):
                        v = const_eval(e, self.w)
                    val = v if v is not None else val + 1
                    out.append(pad + "const %s: u32 = %d;" % (c["name"], val))
            return
        if d.get("kind") != "VarDecl":
            raise Unsupported("decl " + d.get("kind", "?"))
        t = self.w.ctype(d["type"])
        init = d.get("inner")
        if t[0] == "ptr":
            if init:
                s = strip(init[0])
                if s.get("kind") == "UnaryOperator" and s["opcode"] == "&":
                    self.alias[d["id"]] = self.lv(s["inner"][0])
                    return
                if s.get("kind") in ("MemberExpr", "ArraySubscriptExpr") or (
                        s.get("kind") == "DeclRefExpr" and self.w.ctype(s["type"])[0] == "arr"):
                    self.alias[d["id"]] = self.lv(s)
                    return
                if s.get("kind") == "DeclRefExpr" and s["referencedDecl"]["id"] in self.vars:
                    v = self.vars[s["referencedDecl"]["id"]]
                    self.alias[d["id"]] = "(*%s)" % rname(v[3]) if v[1] == "ref" else rname(v[3])
                    return
            raise Unsupported("local pointer " + d["name"])
        self.vars[d["id"]] = ("local", "value", t, d["name"])
        name = rname(d["name"])
        if init and init[0].get("kind") != "InitListExpr":
            c, kk = self.ex(init[0])
            out.append(pad + "let mut %s: %s = %s;" % (name, rty(self.w, t), self.as_kind(c, kk, kind_of(self.w, t))))
        elif init:
            out.append(pad + "let mut %s: %s = %s;" % (name, rty(self.w, t), self.init_list(init[0], t)))
        else:
            out.append(pad + "let mut %s: %s = %s;" % (name, rty(self.w, t), zero(self.w, t)))

    def init_list(self, n, t):
        t = self.w.resolve(t)
        if n.get("kind") == "ImplicitValueInitExpr":
            return zero(self.w, t)
        if n.get("kind") != "InitListExpr":
            c, k = self.ex(n)
            return self.as_kind(c, k, kind_of(self.w, t))
        items = n.get("inner", [])
        if t[0] == "arr":
            vals = [self.init_list(x, t[1]) for x in items]
            if n.get("array_filler") or len(vals) < t[2]:
                filler = zero(self.w, t[1])
                vals += [filler] * (t[2] - len(vals))
            return "[%s]" % ", ".join(vals)
        if t[0] == "struct":
            fields = self.w.records[t[1]]
            parts = []
            for (fname, fq, _bf), x in zip(fields, items):
                parts.append("%s: %s" % (rname(fname), self.init_list(x, parse_type(fq))))
            return "%s { %s, ..%s::ZERO }" % (t[1], ", ".join(parts), t[1])
        if n.get("kind") == "ImplicitValueInitExpr":
            return zero(self.w, t)
        raise Unsupported("init list")

    def emit(self):
        out = [self.fn.sig(self.fns) + " {"]
        body = self.fn.body.get("inner", [])
        for c in body:
            self.stmt(c, out, 1)
        if rty(self.w, self.fn.ret) != "()" and (not body or body[-1].get("kind") != "ReturnStmt"):
            out.append("    // every path above returns")
            out.append("    unreachable!()")
        out.append("}")
        return out


def has_jump(n):
    if n.get("kind") in ("BreakStmt", "ContinueStmt"):
        return True
    if n.get("kind") in ("ForStmt", "WhileStmt", "DoStmt"):
        return False
    return any(has_jump(c) for c in n.get("inner", []) if isinstance(c, dict))


