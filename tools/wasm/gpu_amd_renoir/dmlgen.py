def used_types(w, fns):
    """Every struct reachable from the translated functions and display_mode_lib."""
    seen = []

    def visit_t(t):
        t = w.resolve(t)
        if t[0] in ("ptr", "arr"):
            visit_t(t[1])
        elif t[0] == "fnptr":
            visit_t(t[1])
            for p in t[2]:
                visit_t(p)
        elif t[0] == "struct" and t[1] not in seen and t[1] != "dal_logger":
            if t[1] not in w.records:
                raise Unsupported("struct " + t[1])
            seen.append(t[1])
            for _, fq, _bf in w.records[t[1]]:
                visit_t(parse_type(fq))

    def visit_n(n):
        if isinstance(n, dict):
            if "type" in n and "qualType" in n["type"]:
                try:
                    visit_t(w.ctype(n["type"]))
                except Unsupported:
                    pass
            for c in n.get("inner", []):
                visit_n(c)

    visit_t(("struct", "display_mode_lib"))
    for f in fns.values():
        visit_n(f.node)
    return seen


