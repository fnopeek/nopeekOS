#!/usr/bin/env python3
"""Translate the DCN 2.1 Display Mode Library from C to Rust, mechanically.

DML is ~10k lines of floating-point code from the hardware team; it is not
transcribed by hand. clang parses each file with the whole-DC oracle's flags
(oracle/build.sh) and dumps the typed AST as JSON. In that AST every
implicit C conversion is a node of its own (IntegralToFloating, FloatingCast,
IntegralCast ...), so the translation is a walk that writes each node as the
Rust expression with the same value: no conversion is guessed.

    python3 dmlgen.py            # rewrite the generated files in src/
    python3 dmlgen.py --check    # fail if any is not what it would write

Output: src/display_mode_structs.rs (every struct, typedef and enum constant
the translated code names) and one module per C file in FILES. A function in
HAND is written by hand in src/dml_math.rs instead (type punning through a
pointer); the generator only names it.

Mapping. `double` f64, `float` f32, `int` i32, `unsigned int` u32, `bool`
bool, an enum u32 (its constants are u32 consts). A struct pointer parameter
is `&mut S` (`&S` if const); a scalar pointer parameter is a slice when the
body subscripts it (or hands it on as one) and a reference otherwise. A
local `T *p = &x;` that is never reassigned is an alias: every use of `p` is
written as `x`. Float to integer goes through the x86 truncating conversion
(`f2i32`, `f2u32` in dml_math.rs), which is what gcc emits, not Rust's
saturating `as`.
"""
