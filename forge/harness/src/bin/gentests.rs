//! Emit the kernel's on-device test modules as Rust byte arrays.
//!
//! They are built here rather than in the kernel because assembling wasm needs
//! `wat`, which is a std crate — and because a module that is checked on the
//! host first is one fewer unknown when the device says no.

/// Run a module here the same way the kernel will, and report what came out.
fn forge_harness_run(wasm: &[u8], arg: u32, fuel: i64) -> (u32, u32) {
    let out = std::process::Command::new(std::env::current_exe().unwrap().parent().unwrap().join("forge_harness"))
        .arg("--oneshot")
        .arg(hex(wasm))
        .arg(arg.to_string())
        .arg(fuel.to_string())
        .output()
        .expect("forge_harness --oneshot");
    let text = String::from_utf8_lossy(&out.stdout);
    let mut it = text.split_whitespace();
    let r: u32 = it.next().unwrap().parse().unwrap();
    let t: u32 = it.next().unwrap().parse().unwrap();
    (r, t)
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn main() {
    let cases: &[(&str, &str)] = &[
        ("ARITH", "(module (func (export \"f\") (param i32) (result i32) \
            local.get 0 i32.const 3 i32.mul i32.const 7 i32.add))"),
        ("CALLS", "(module \
            (func $g (param i32) (result i32) local.get 0 i32.const 2 i32.mul) \
            (func $h (param i32) (result i32) local.get 0 call $g call $g) \
            (func (export \"f\") (param i32) (result i32) local.get 0 call $h i32.const 1 i32.add))"),
        ("MEM", "(module (memory 1) (data (i32.const 16) \"nopeek\") \
            (func (export \"f\") (param i32) (result i32) \
              i32.const 0 local.get 0 i32.store \
              i32.const 0 i32.load i32.const 16 i32.load8_u i32.add))"),
        ("LOOP", "(module (func (export \"f\") (param i32) (result i32) \
            (local i32) (local i32) \
            local.get 0 i32.const 255 i32.and local.set 0 \
            (block $done (loop $top \
              local.get 1 local.get 0 i32.ge_u br_if $done \
              local.get 2 local.get 1 i32.add local.set 2 \
              local.get 1 i32.const 1 i32.add local.set 1 \
              br $top)) \
            local.get 2))"),
        ("INDIRECT", "(module \
            (type $t (func (param i32) (result i32))) \
            (func $a (type $t) local.get 0 i32.const 10 i32.add) \
            (func $b (type $t) local.get 0 i32.const 100 i32.mul) \
            (table 2 funcref) (elem (i32.const 0) $a $b) \
            (func (export \"f\") (param i32) (result i32) \
              i32.const 5 local.get 0 i32.const 1 i32.and call_indirect (type $t)))"),
        ("FLOAT", "(module (func (export \"f\") (param i32) (result i32) \
            local.get 0 f64.convert_i32_s f64.const 2.5 f64.mul f64.floor \
            i32.trunc_sat_f64_s))"),
        ("GROW", "(module (memory 1 4) (func (export \"f\") (param i32) (result i32) \
            i32.const 1 memory.grow drop \
            i32.const 70000 local.get 0 i32.store i32.const 70000 i32.load \
            memory.size i32.add))"),
        ("TRAP_UNREACHABLE", "(module (func (export \"f\") (param i32) (result i32) \
            local.get 0 if unreachable end i32.const 5))"),
        ("TRAP_OOB", "(module (memory 1) (func (export \"f\") (param i32) (result i32) \
            local.get 0 i32.load))"),
        ("TRAP_DIV", "(module (func (export \"f\") (param i32) (result i32) \
            i32.const 100 local.get 0 i32.div_u))"),
        ("TRAP_TABLE", "(module \
            (type $t (func (param i32) (result i32))) \
            (func $a (type $t) local.get 0) \
            (table 2 funcref) (elem (i32.const 0) $a) \
            (func (export \"f\") (param i32) (result i32) \
              i32.const 5 local.get 0 call_indirect (type $t)))"),
        ("TRAP_FUEL", "(module (func (export \"f\") (param i32) (result i32) \
            (local i32) \
            (block $done (loop $top \
              local.get 1 i32.const 1 i32.add local.set 1 \
              local.get 0 br_if $top)) \
            local.get 1))"),
    ];

    // (name, argument, fuel budget)
    let args: &[(&str, u32, i64)] = &[
        ("ARITH", 11, -1),
        ("CALLS", 5, -1),
        ("MEM", 12345, -1),
        ("LOOP", 100, -1),
        ("INDIRECT", 0, -1),
        ("INDIRECT", 1, -1),
        ("FLOAT", 7, -1),
        ("GROW", 4242, -1),
        ("TRAP_UNREACHABLE", 0, -1),
        ("TRAP_UNREACHABLE", 1, -1),
        ("TRAP_OOB", 0, -1),
        ("TRAP_OOB", 65536, -1),
        ("TRAP_DIV", 4, -1),
        ("TRAP_DIV", 0, -1),
        ("TRAP_TABLE", 0, -1),
        ("TRAP_TABLE", 9, -1),
        ("TRAP_FUEL", 0, 100_000),
        ("TRAP_FUEL", 1, 100_000),
    ];

    let mut out = String::from(
        "//! Small wasm modules for the on-device check, and what they must\n         //! produce. Generated by `forge/harness --bin gentests`.\n         //!\n         //! The modules are bytes because assembling wasm needs a std crate.\n         //! The EXPECTATIONS are not written by hand either — every one was\n         //! produced by running the module here, on a compiler whose output is\n         //! checked against the interpreter case by case. So the device is\n         //! compared against something that was measured, not against\n         //! somebody's arithmetic.\n\n         pub struct Case {\n         \x20   pub name: &'static str,\n         \x20   pub wasm: &'static [u8],\n         \x20   pub arg: u32,\n         \x20   pub want: u32,\n         \x20   /// `forge_core::trap::*`\n         \x20   pub trap: u32,\n         \x20   /// -1 for the default budget.\n         \x20   pub fuel: i64,\n         }\n\n",
    );

    let mut blobs = std::collections::BTreeMap::new();
    for (name, src) in cases {
        let wasm = wat::parse_str(src).unwrap_or_else(|e| panic!("{name}: {e}"));
        let m = forge_core::compile(&wasm).unwrap_or_else(|e| panic!("{name}: {e}"));
        assert!(
            m.funcs
                .iter()
                .all(|o| matches!(o, forge_core::codegen::Outcome::Done(_))),
            "{name}: nicht vollstaendig uebersetzt"
        );
        out.push_str(&format!(
            "pub const {name}: &[u8] = &[\n    {}\n];\n\n",
            wasm.iter()
                .map(|b| format!("0x{b:02x}"))
                .collect::<Vec<_>>()
                .chunks(12)
                .map(|c| c.join(", "))
                .collect::<Vec<_>>()
                .join(",\n    ")
        ));
        blobs.insert(*name, wasm);
    }

    out.push_str("pub const CASES: &[Case] = &[\n");
    for (name, arg, fuel) in args {
        let wasm = &blobs[name];
        let (got, trap) = forge_harness_run(wasm, *arg, *fuel);
        out.push_str(&format!(
            "    Case {{ name: \"{name}\", wasm: {name}, arg: {arg}, want: {got}, trap: {trap}, fuel: {fuel} }},\n"
        ));
        eprintln!("  {name:<18} arg {arg:<8} -> {got} (trap {trap})");
    }
    out.push_str("];\n");

    std::fs::write("../../kernel/src/forge_tests.rs", out).unwrap();
    eprintln!("{} Module, {} Faelle", cases.len(), args.len());
}
